"""Harness for SkyyProfiles 0.1.19 (the bridge profile:fn:act for SkyyMenu 0.3.71's Social tab; tools/profiles_0_1_19_patch.py).
GENERATED by tools/profiles_0_1_19_patch.py from the 0.1.18 harness (every 0.1.18 check runs again on the 0.1.19 jar), plus
  ACT (exec, a scratch players folder, no engine): list = the old list's rows (active first, live, deleted with its undo line, Delete
      only where the old page shows it), roster = the class cards, newname, rename (+ a refused name, a deleted / unknown id), delask
      (the question; the active / last profile refused), delete (+ a second delete of the same id = refused, nothing twice), restore, an
      unknown op / a bad argument = "-..." (never throws), cancreate refusals (no class, not selectable, slots full) and the offline
      refusal of the engine part; the setup registers profile:fn:act (bytecode)
Build first:
    python tools/profiles_0_1_19_patch.py && python SkyyProfiles/build_skyyprofiles_0.1.19.py
    python SkyyProfiles/test_skyyprofiles_0.1.19.py [--keep]
Phases (tools/harness_kit.py, fresh child JVMs, -Xverify:all, TEMP / TMP in tools/dev/scratch/prof18/prof):
  A   verify   every class loads + initialises
  C   compare  0.1.17 -> 0.1.18: exactly the planned members (EXPECT); non-class entries: manifest.json only
  X   exec     ProfRoster on a stand-in skyy.bridge:
               X1 no class:fn:emblem (no SkyyClasses 0.1.36) = today's look: iconOf = the first weapon / the Create-new orb; cardIcons = the weapons
               X2 with a stand-in class:fn:emblem: iconOf = the emblem (an alias goes through canon: Shaman -> Monk), no class = the orb,
                  an unknown class = the weapon fallback; cardIcons = emblem + 2 weapons (Locked while the class is not released); a
                  throwing / non-String answer = today's look
               X3 the Create Profile page calls cardIcons, the profile list iconOf (bytecode)
  Y   0.1.18 (exec): two weapons per class = Skyy's primary + secondary table; SkyyArmory's soul cage / gauntlets show their vanilla
               stand-in when their asset is not loaded (this JVM has no assets); vanilla ids pass through shownIcon unchanged;
               the Create Profile markup: 140 px cards, 108 px item frames, the 24 px name; the profile list keeps 92 / 64
  AA  engine-access audit
"""
import os, sys, json

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TOOLS = os.path.join(ROOT, "tools")
sys.path.insert(0, TOOLS)
import skyybuild as B
import harness_kit as HK
import perfworld_kit as PW

VERSION = "0.1.19"
JAR = os.path.abspath(HK.arg("--jar", os.path.join(HERE, "SkyyProfiles-%s.jar" % VERSION)))
OLD_JAR = os.path.join(HERE, "SkyyProfiles-0.1.18.jar")
SCRATCH = os.path.abspath(HK.arg("--dir", os.path.join(TOOLS, "dev", "scratch", "oldmenu3", "prof")))
PKG = "com.skyy.profiles."
EXPECT = {"SkyyProfilesPlugin": ["~m setup"],                          # 0.1.19: + profile:fn:act (and the version text)
          # the version texts only
          "CfgFn": ["~m opExport"], "CfgRows": ["~m header"], "ProfCfg": ["~m capMigrate"], "ProfDel": ["~m archiveLocked"]}
ADDED = ["ActFn"]


def run_exec(out, jar, scratch, _home):   # 0.1.19: + ACT
    from jpype import JClass, JImplements, JOverride, JString
    K = HK.Child(out)
    HK.jvm([B.SERVER_JAR, jar, B.JAVASSIST], verify=True)
    R, Cfg = JClass(PKG + "ProfRoster"), JClass(PKG + "ProfCfg")
    br = Cfg.bridge()
    br.remove("class:fn:emblem")
    br.remove("class:list")

    @JImplements("java.util.function.Function")
    class Fn(object):
        def __init__(self, f):
            self.f = f

        @JOverride
        def apply(self, o):
            return self.f(o)
    names = [str(x) for x in R.NAMES]
    icons = [str(x).split(",") for x in R.ICONS]
    our = dict(zip([str(x) for x in R.OUR_IDS], [str(x) for x in R.OUR_ALT]))
    shown = [[our.get(x, x) for x in w] for w in icons]      # 0.1.18: no assets in this JVM = SkyyArmory's items show their stand-in
    # ---- X1 no bridge
    for n, w, sw in zip(names, icons, shown):
        K.eq(str(R.iconOf(n)), w[0], "X1: %s profile card without class:fn:emblem = its first weapon" % n)
        K.eq([str(x) for x in R.cardIcons(n, ",".join(w), True)], sw, "X1: %s Create card without the bridge = its weapons" % n)
    K.eq(str(R.iconOf("")), str(R.NEW_ICON), "X1: no class = the Create-new orb")
    K.eq(str(R.iconOf(None)), str(R.NEW_ICON), "X1: null class = the Create-new orb")
    # ---- X2 a stand-in bridge
    asked = []

    def em(o):
        s = str(o)
        asked.append(s)
        base, _, lk = s.partition(":")
        if base not in names:
            return JString("")
        return JString("SkyyClasses_Emblem_" + base + ("_Locked" if lk == "locked" else ""))
    br.put("class:fn:emblem", Fn(em))
    for n, w, sw in zip(names, icons, shown):
        K.eq(str(R.iconOf(n)), "SkyyClasses_Emblem_" + n, "X2: %s profile card = its emblem" % n)
        K.eq([str(x) for x in R.cardIcons(n, ",".join(w), True)], ["SkyyClasses_Emblem_" + n] + sw[:2], "X2: %s Create card = emblem + 2 weapons" % n)
        K.eq([str(x) for x in R.cardIcons(n, ",".join(w), False)][0], "SkyyClasses_Emblem_%s_Locked" % n, "X2: %s not released = the Locked emblem" % n)
        K.check(len(R.cardIcons(n, ",".join(w), True)) <= 3, "X2: %s Create card stays within its 3 cells" % n)
    del asked[:]
    K.eq(str(R.iconOf("Shaman")), "SkyyClasses_Emblem_Monk", "X2: an old class name goes through canon (Shaman -> Monk)")
    K.eq(asked, ["Monk"], "X2: ... the bridge is asked for Monk")
    K.eq(str(R.iconOf("")), str(R.NEW_ICON), "X2: no class = still the Create-new orb (the bridge not asked)")
    K.eq(str(R.iconOf("Necromancer")), str(R.EXTRA_ICON), "X2: an unknown class = the weapon fallback")
    br.put("class:fn:emblem", Fn(lambda o: 5))
    K.eq(str(R.iconOf(names[0])), icons[0][0], "X2: a non-String answer = today's look")

    def boom(o):
        raise RuntimeError("boom")
    br.put("class:fn:emblem", Fn(boom))
    K.eq(str(R.iconOf(names[0])), icons[0][0], "X2: a throwing bridge = today's look (never throws)")
    K.eq([str(x) for x in R.cardIcons(names[0], ",".join(icons[0]), True)], shown[0], "X2: ... and the Create card keeps its weapons")
    br.remove("class:fn:emblem")
    # ---- X3 bytecode
    gr = PW.calls(jar)
    K.check(PKG + "ProfRoster.cardIcons" in gr.get("ProfilePage.buildCreate", set()), "X3: the Create Profile cards use cardIcons (bytecode)")
    K.check(PKG + "ProfRoster.iconOf" in gr.get("ProfilePage.buildList", set()), "X3: the profile list still uses iconOf (bytecode)")
    K.check(PKG + "ProfRoster.emblem" in gr.get("ProfRoster.iconOf", set()), "X3: iconOf asks emblem first (bytecode)")
    # ---- Y 0.1.18: Skyy's primary + secondary table (2026-10-18; Warrior = "Sword + Spear (Recommended)")
    want = {"Archer": ["Weapon_Shortbow_Iron", "Weapon_Crossbow_Iron"], "Warrior": ["Weapon_Sword_Iron", "Weapon_Spear_Iron"],
            "Mage": ["Weapon_Staff_Iron", "Weapon_Spellbook_Frost"], "Berserker": ["Weapon_Battleaxe_Iron", "Weapon_Mace_Iron"],
            "Priest": ["Weapon_Wand_Wood", "Weapon_Wand_SoulCage_Copper"], "Assassin": ["Weapon_Daggers_Iron", "Weapon_Kunai"],
            "Monk": ["Weapon_Staff_Bo_Wood", "Weapon_Fist_Gauntlets_Copper"],
            "Spellblade": ["Weapon_Longsword_Spectral", "Weapon_Longsword_Flame"]}
    K.eq(dict(zip(names, icons)), want, "Y1: the fallback table = emblem + Skyy's primary + secondary weapon per class")
    K.eq(our, {"Weapon_Wand_SoulCage_Copper": "Weapon_Spellbook_Grimoire_Brown", "Weapon_Fist_Gauntlets_Copper": "Weapon_Staff_Bo_Bamboo"},
         "Y1: SkyyArmory's items + their vanilla stand-ins (0.1.17's icons)")
    K.eq(str(R.shownIcon("Weapon_Wand_SoulCage_Copper")), "Weapon_Spellbook_Grimoire_Brown", "Y2: no soul cage asset loaded = the stand-in")
    K.eq(str(R.shownIcon("Weapon_Fist_Gauntlets_Copper")), "Weapon_Staff_Bo_Bamboo", "Y2: no gauntlet asset loaded = the stand-in")
    K.eq(str(R.shownIcon("Weapon_Sword_Iron")), "Weapon_Sword_Iron", "Y2: a vanilla id as it is")
    K.eq(str(R.shownIcon(None)), "", "Y2: null = empty (never throws)")
    br.put("class:fn:emblem", Fn(em))
    K.eq([str(x) for x in R.cardIcons("Priest", R.ICONS[names.index("Priest")], True)],
         ["SkyyClasses_Emblem_Priest", "Weapon_Wand_Wood", "Weapon_Spellbook_Grimoire_Brown"], "Y2: Priest card without SkyyArmory = emblem + wand + stand-in")
    br.remove("class:fn:emblem")
    wt = dict(zip(names, [str(x) for x in R.WTEXT]))
    K.eq((wt["Priest"], wt["Mage"]), ("Wands / Soul Cages", "Staves / Spellbooks"), "Y1: the weapon texts match the icons")
    pd = str(R.DESCS[names.index("Priest")])
    K.check("Soul Cage" in pd and "spellbook" not in pd.lower(), "Y1: the Priest description names the Soul Cage, no spellbook")
    K.check(PKG + "ProfRoster.shownIcon" in gr.get("ProfRoster.cardIcons", set()), "Y2: cardIcons maps the weapons through shownIcon (bytecode)")
    import zipfile
    page = zipfile.ZipFile(jar).read("com/skyy/profiles/ProfilePage.class").decode("latin-1")
    K.check("Height: 140" in page and "Width: 108, Height: 108" in page and "FontSize: 24" in page,
            "Y3: the Create Profile markup has the 140 px cards, 108 px item frames and the 24 px class name")
    K.check("Height: 92" in page and "Width: 64, Height: 64" in page, "Y3: the profile list keeps the 92 px SKYY CARD with 64 px frames")

    # ---- ACT 0.1.19: profile:fn:act on a scratch players folder (no engine: the ops that need the player in a world refuse "not online")
    import uuid as _uuid
    Paths = JClass("java.nio.file.Paths")
    Sto, Del, Act = JClass(PKG + "ProfStore"), JClass(PKG + "ProfDel"), JClass(PKG + "ActFn")
    pdir = os.path.join(scratch, "act", "players")
    os.makedirs(pdir, exist_ok=True)
    Sto.DIR = Paths.get(pdir)
    for sub_ in ("switching", "inventories", "archive"):
        os.makedirs(os.path.join(scratch, "act", sub_), exist_ok=True)
    Sto.SWDIR = Paths.get(os.path.join(scratch, "act", "switching"))
    Sto.INVDIR = Paths.get(os.path.join(scratch, "act", "inventories"))
    Del.ARCDIR = Paths.get(os.path.join(scratch, "act", "archive"))
    Sto.LOGF = Paths.get(os.path.join(scratch, "act", "profiles.log"))
    U = JClass("java.util.UUID")
    u = U.fromString(str(_uuid.UUID(int=0x5151)))
    now = int(JClass("java.lang.System").currentTimeMillis())
    lines = ["active=1", "p.1.name=Main", "p.1.class=Archer", "p.1.created=%d" % (now - 86400000), "p.1.lastPlayed=%d" % now,
             "p.2.name=Iron", "p.2.class=Warrior", "p.2.created=%d" % (now - 3600000), "p.2.lastPlayed=%d" % (now - 600000),
             "p.3.name=Old", "p.3.class=Mage", "p.3.created=%d" % (now - 7200000), "p.3.lastPlayed=%d" % (now - 7200000)]
    with open(os.path.join(pdir, str(u) + ".properties"), "w") as f_:
        f_.write("\n".join(lines) + "\n")
    Sto.DATA.remove(u)
    fn = Act()
    OA = JClass("java.lang.Object")
    from jpype import JArray as _JA

    def act(*a):
        return str(fn.apply(_JA(OA)(list(a))))
    ls = act("list", u).split("\n")
    K.check(ls[0].startswith("h|3|") and ls[0].split("|")[7] == "0", "ACT list header: 3 live profiles, an active one (%s)" % ls[0])
    rows = [r.split("|") for r in ls[1:]]
    K.eq([(r[1], r[2].split(" ")[-1] if r[2] else "", r[4], r[6]) for r in rows][:3],
         [("1", "Main", "active", "0"), ("2", "Iron", "live", "1"), ("3", "Old", "live", "1")],
         "ACT list rows = the old list (id, name, state, Delete only on a live non-active profile)")
    K.check("playing now" in rows[0][5] and "last played" in rows[1][5], "ACT list: the old card's third line (%s / %s)" % (rows[0][5], rows[1][5]))
    ro = act("roster", u).split("\n")
    K.check(len(ro) >= 7 and all(r.startswith("c|") and len(r.split("|")) == 8 for r in ro) and ro[0].split("|")[1] == "Archer",
            "ACT roster = one c| line per class card (%d)" % len(ro))
    nn = act("newname", u, "Main")
    K.check(len(nn) >= 2 and nn != "Main", "ACT newname = a fresh name (%s)" % nn)
    r = act("rename", u, "2", "Copper")
    K.check(r.startswith("+") and str(Sto.load(u).getProperty("p.2.name")) == "Copper", "ACT rename = renameProfile (%s)" % r)
    r = act("rename", u, "2", "x")
    K.check(r.startswith("-") and str(Sto.load(u).getProperty("p.2.name")) == "Copper", "ACT rename: a too-short name refused, nothing changed (%s)" % r)
    K.check(act("rename", u, "9", "Gold").startswith("-") and act("rename", u, "../1", "Gold").startswith("-"), "ACT rename: an unknown / junk id refused")
    q = act("delask", u, "3")
    K.check(q.startswith("=Delete profile ") and "undo" in q, "ACT delask = the old page's question (%s)" % q)
    K.check(act("delask", u, "1").startswith("-You are playing"), "ACT delask on the active profile = refused (the old rule)")
    d1 = act("delete", u, "3")
    K.check(d1.startswith("+") and "is deleted" in d1 and bool(Sto.isDel(Sto.load(u), "3")), "ACT delete = ProfDel.delete (%s)" % d1)
    d2 = act("delete", u, "3")
    K.check(d2.startswith("-") and "already deleted" in d2, "ACT delete twice (a double click / a stale page) = refused, deleted once (%s)" % d2)
    ls = act("list", u).split("\n")
    rows = [r.split("|") for r in ls[1:]]
    K.check([r[4] for r in rows] == ["active", "live", "del"] and "restore it within" in rows[2][5] and rows[2][6] == "0",
            "ACT list after the delete: the deleted one last with its undo line, no Delete on it (%s)" % [r[4] for r in rows])
    K.check(act("delask", u, "2").startswith("=") and act("delask", u, "1").startswith("-"), "ACT delask: Iron may go, the active one never")
    rs = act("restore", u, "3")
    K.check(rs.startswith("+") and "is back" in rs and bool(Sto.live(Sto.load(u), "3")), "ACT restore = ProfDel.restore (%s)" % rs)
    K.check(act("restore", u, "3").startswith("-"), "ACT restore twice = refused (not deleted)")
    K.check(act("nope", u) == "-Unknown profile action." and str(fn.apply(None)) == "-Unknown profile action." and str(fn.apply("x")) == "-Unknown profile action."
            and act("list", "not-a-uuid").startswith("-"), "ACT an unknown op / bad argument = '-...' (never throws)")
    K.eq(act("cancreate", u, ""), "-Select a class first.", "ACT cancreate with no class = the old page's line")
    K.check(act("cancreate", u, "Spellblade").endswith("is not available.") or act("cancreate", u, "Spellblade") == "-You are not online.",
            "ACT cancreate on a class that is not selectable = refused")
    K.eq(act("cancreate", u, "Archer"), "-You are not online.", "ACT cancreate: every file check passed, the engine part needs the player online")
    K.eq(act("create", u, "Archer", "Peach"), "-You are not online.", "ACT create offline = refused, nothing created")
    K.eq(int(Sto.count(Sto.load(u))), 3, "ACT ... still 3 profiles")
    # fix (oldmenu3 critic HIGH): cancreate is asked while SkyyMenu's Social tab is the open page -> refuse's open-menu line must not stop it
    pl_ = "Close the open menu first, then switch profiles."
    K.check(Act.pageOnly(pl_, True) is None, "FIX cancreate from the open Social tab: refuse's open-menu line is let through")
    K.eq(str(Act.pageOnly(pl_, False)), pl_, "FIX create (the page already closed) keeps the open-menu refusal")
    K.eq(str(Act.pageOnly("You are in combat - wait 5 s before switching profiles.", True)), "You are in combat - wait 5 s before switching profiles.",
         "FIX cancreate still refuses combat / death (refuse checks those before the page)")
    K.eq(str(Act.pageOnly("You cannot switch profiles while dead.", True)), "You cannot switch profiles while dead.", "FIX cancreate still refuses a dead player")
    K.check(Act.pageOnly(None, True) is None, "FIX no refusal stays no refusal")
    K.check(pl_.encode() in zipfile.ZipFile(jar).read("com/skyy/profiles/ProfSwitch.class"), "FIX ProfSwitch.refuse still answers exactly that open-menu line")
    gr2 = PW.calls(jar)
    K.check(PKG + "ProfDel.delete" in gr2.get("ActFn.delete", set()) and PKG + "ProfStore.renameProfile" in gr2.get("ActFn.rename", set())
            and PKG + "ProfSwitch.createAndSwitch" in gr2.get("ActFn.create", set()) and PKG + "ProfSwitch.refuse" in gr2.get("ActFn.canCreate", set())
            and PKG + "ActFn.pageOnly" in gr2.get("ActFn.canCreate", set())
            and PKG + "ProfilePage.shownIds" in gr2.get("ActFn.list", set()), "ACT bytecode: the ops call the old page's code (delete / rename / createAndSwitch / refuse / shownIds)")
    K.check("profile:fn:act" in zipfile.ZipFile(jar).read("com/skyy/profiles/SkyyProfilesPlugin.class").decode("latin-1"), "ACT the setup registers profile:fn:act")
    K.save()


if __name__ == "__main__":
    HK.run(name="SkyyProfiles", version=VERSION, jar=JAR, old_jar=OLD_JAR, pkg=PKG, scratch=SCRATCH, expect=EXPECT, added=ADDED,
           phases=[("exec", run_exec)], script=__file__)
