def run_compare(out, jar, old_jar, pkg, expect, added):
    from jpype import JClass
    K = HK.Child(out)
    HK.jvm([B.JAVASSIST], verify=False)
    CPc = JClass("javassist.ClassPool")
    IP = JClass("javassist.bytecode.InstructionPrinter")
    import re

    def pool_of(j):
        p_ = CPc(False)
        p_.appendSystemPath()
        p_.appendClassPath(B.SERVER_JAR)
        p_.appendClassPath(j)
        return p_
    pa, pb = pool_of(old_jar), pool_of(jar)

    def members(p_, cn):
        c_ = p_.get(cn)
        d_ = {}
        for f_ in c_.getDeclaredFields():
            d_["f " + str(f_.getName())] = str(f_.getSignature()) + " " + str(f_.getModifiers())

        def code(b_):
            mi_ = b_.getMethodInfo()
            ca_ = mi_.getCodeAttribute()
            if ca_ is None:
                return ""
            it_ = ca_.iterator()
            cpl_ = mi_.getConstPool()
            lines_ = []
            while it_.hasNext():
                pos_ = it_.next()
                ln_ = re.sub(r"^ldc_w ", "ldc ", re.sub(r"#\d+ = ", "", str(IP.instructionString(it_, pos_, cpl_))))
                lines_.append(re.sub(r"^((?:if\w*|goto(?:_w)?|jsr(?:_w)?)) -?\d+$", r"\1", ln_))
            return str(b_.getModifiers()) + "\n" + "\n".join(lines_)
        for m_ in c_.getDeclaredMethods():
            d_["m " + str(m_.getName()) + str(m_.getSignature())] = code(m_)
        for m_ in c_.getDeclaredConstructors():
            d_["c " + str(m_.getSignature())] = code(m_)
        ci = c_.getClassInitializer()
        if ci is not None:
            d_["<clinit>"] = code(ci)
        return d_
    na, nb = HK.jar_classes(old_jar), HK.jar_classes(jar)
    K.eq(sorted(set(nb) - set(na)), sorted(pkg + a for a in ADDED), "C: classes added (ShHand, ShRain, ShSoil)")
    K.eq(sorted(set(na) - set(nb)), [], "C: classes removed")
    diffs, same = {}, []
    for cn in sorted(set(na) & set(nb)):
        ma, mb = members(pa, cn), members(pb, cn)
        dd = sorted(k for k in set(ma) | set(mb) if ma.get(k) != mb.get(k))
        short = cn[len(pkg):] if cn.startswith(pkg) else cn
        if dd:
            diffs[short] = sorted(("+" if k not in ma else ("-" if k not in mb else "~")) + k.split("(")[0] for k in dd)
        else:
            same.append(short)
    print("C. class compare 0.3.2 -> 0.4: %d classes identical, %d differ" % (len(same), len(diffs)))
    for k in sorted(diffs):
        print("   %-18s %s" % (k, ", ".join(diffs[k])))
    K.eq(sorted(diffs), CHANGED, "C: the classes that differ are exactly the 0.4 set (every other class identical)")
    # the members 0.4 must NOT lose (removed on purpose: the overview / craft tab / menu view of ShPage, ShFn's menu route, the old upgrade)
    gone = dict((k, [x for x in v if x.startswith("-")]) for k, v in diffs.items())
    allowed_gone = {"ShPage": ["-f fromTotem", "-f fromMenu", "-f oN", "-f oName", "-f oSub", "-f oSt", "-f oStC", "-m fillCraft", "-m fillOverview",
                               "-m handedOff", "-c "],
                    "ShPageFn": ["-f totem", "-c "], "ShFn": ["-m firstKind"], "ShCore": ["-m upgrade"]}
    bad = {}
    for k, v in gone.items():
        rest = [x for x in v if not any(x.startswith(a) for a in allowed_gone.get(k, []))]
        if rest:
            bad[k] = rest
    K.check(not bad, "C: nothing else removed: %s" % bad)
    K.check(all(c in same for c in ("ShKind", "ShMath", "ShInv", "ShPay", "ShWorlds", "ShRole", "ShWorld2", "ShPlace", "ShAdmin", "ShGiveFn", "ShSnd")),
            "C: the production maths, inventory moves, payments, worlds, roles, placing, /shardadmin and shard:fn:give are untouched")
    # non-class entries
    za, zb = zipfile.ZipFile(old_jar), zipfile.ZipFile(jar)
    ea = set(n for n in za.namelist() if not n.endswith(".class"))
    eb = set(n for n in zb.namelist() if not n.endswith(".class"))
    benches = ["Server/Item/Items/SkyyShards/Benches/Skyy_TotemBench_%s.json" % k for k in KINDS] + \
        ["Common/Blocks/SkyyShards/TotemBench_%s.png" % k for k in KINDS] + ["Common/Icons/ItemsGenerated/Skyy_TotemBench_%s.png" % k for k in KINDS]
    K.eq(sorted(eb - ea), sorted(benches), "C: new non-class entries = the 6 bench documents + textures + icons")
    K.eq(sorted(ea - eb), [], "C: no non-class entry removed")
    changed = sorted(n for n in ea & eb if za.read(n) != zb.read(n))
    totems = sorted(n for n in ea if n.startswith("Server/Item/Items/SkyyShards/Totems/Skyy_Totem_") and not n.endswith("_Block.json")
                    and "TotemMod" not in n and "TotemBlock" not in n)
    K.eq(len(totems), 20, "C: 20 totem item documents")
    K.eq(changed, sorted(["manifest.json", "Server/Languages/en-US/server.lang"] + totems), "C: changed = manifest, server.lang, the 20 totem item documents")
    for n in totems:
        a, b = json.loads(za.read(n)), json.loads(zb.read(n))
        ib = b.pop("Interactions", None)
        K.check(a == b and ib == {"Secondary": {"RequireNewClick": True, "Interactions": [{"Type": "OpenCustomUI", "Page": {"Id": "SkyyTotemUse"}}]}},
                "C: %s gains only the Secondary -> SkyyTotemUse interaction (RequireNewClick: one use per click)" % os.path.basename(n))
    K.notes.append("C: %d identical, changed %s" % (len(same), sorted(diffs)))
    K.save()


