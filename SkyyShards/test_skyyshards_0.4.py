def run_live(out, jar, scratch, home):
    from jpype import JClass
    K = HK.Child(out)
    HK.jvm([B.SERVER_JAR, jar], verify=True)
    Cfg, St, Snd = JClass(PKG + "ShCfg"), JClass(PKG + "ShStore"), JClass(PKG + "ShSnd")
    Paths = JClass("java.nio.file.Paths")
    mods = os.path.dirname(home)
    sh = home
    isl = os.path.join(mods, "Skyy_SkyyIslands")
    if not os.path.isdir(isl) and os.path.isdir(os.path.join(LIVE_DIR, "Skyy_SkyyIslands")):
        import shutil
        shutil.copytree(os.path.join(LIVE_DIR, "Skyy_SkyyIslands"), isl)   # read-only source, scratch copy
    h_sh = HK.tree_hash(sh)
    h_is = HK.tree_hash(isl) if os.path.isdir(isl) else None
    for start in (1, 2):
        Cfg.DIR = Paths.get(sh)
        Cfg.FILE = Paths.get(os.path.join(sh, "config.properties"))
        r = str(Cfg.loadCfg(True))
        Snd.load(Paths.get(sh))
        St.DIR = Paths.get(os.path.join(sh, "shards"))
        St.CACHE.clear()
        K.check(not r.startswith("default"), "D start %d: the live config.properties is read, not rewritten" % start)
        K.check(HK.tree_hash(sh) == h_sh, "D start %d: the copied Skyy_SkyyShards is byte-identical (nothing written)" % start)
    K.check(int(Cfg.benchCap(1)) == 2 and int(Cfg.BENCH_COINS[2]) == 25000 and int(Cfg.HAND_CD) == 120 and str(Cfg.benchItems(2, 2)) == "Skyy_Ench_Wheat:2",
            "D the 0.4 rows are missing in the live file -> their defaults (no file migration)")
    if h_is is not None:
        K.check(HK.tree_hash(isl) == h_is, "D the copied Skyy_SkyyIslands is byte-identical")
    shards = os.path.join(sh, "shards")
    if os.path.isdir(shards):
        for f in sorted(os.listdir(shards)):
            if f.endswith(".properties"):
                k = f[:-11]
                p = St.get(k)
                K.check(p is not None, "D the live profile file %s reads (and migrates if needed)" % f)
        K.notes.append("D live shard files: %d, migrated %d" % (len([f for f in os.listdir(shards) if f.endswith(".properties")]), int(St.MIGRATED.get())))
    else:
        K.notes.append("D the live data has no shard profile files yet (no shard placed) - the migration ran on the X3 0.3.2 files")
    K.save()


