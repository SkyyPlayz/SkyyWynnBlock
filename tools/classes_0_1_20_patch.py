ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "SkyyClasses", "build_skyyclasses_0.1.19.py")
dst = os.path.join(ROOT, "SkyyClasses", "build_skyyclasses_0.1.20.py")
