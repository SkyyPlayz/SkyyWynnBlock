def string_spans(text):
    """(start, end) offsets of every string literal token of the script but the module docstring (the first one)"""
    offs = [0]
    for ln in text.split(LF):
        offs.append(offs[-1] + len(ln) + 1)
    out, first = [], True
    for t in tokenize.generate_tokens(io.StringIO(text).readline):
        if t.type == tokenize.STRING or t.type == getattr(tokenize, "FSTRING_MIDDLE", -1):
            if first and t.type == tokenize.STRING:
                first = False
                continue
            out.append((offs[t.start[0] - 1] + t.start[1], offs[t.end[0] - 1] + t.end[1]))
    return out


def rename(text):
    parts, last = [], 0
    for a, b in string_spans(text):
        seg = text[a:b]
        for o, n in NAMES:
            seg = seg.replace(o, n)
        parts.append(text[last:a])
        parts.append(seg)
        last = b
    parts.append(text[last:])
    return "".join(parts)


