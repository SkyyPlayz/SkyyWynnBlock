"""Derive SkyyEssentials/build_skyyessentials_0.1.11.py from 0.1.10 (build_skyyessentials_0.1.10.py = the tools/deploy_set.py SET pin).
Run:  python tools/essentials_0_1_11_patch.py   then   python SkyyEssentials/build_skyyessentials_0.1.11.py   (never --deploy: coordinated deploy)
Check: python SkyyEssentials/test_skyyessentials_0.1.11.py   (bare JVM, -Xverify:all; nothing is deployed)
SkyyEssentials uses patch scripts since 0.1.4: edit THIS file, never the generated build script.

0.1.11 = THE MISSING 'Compost_Soft' RESOURCE TYPE (2026-10-16 CROPS GONE, docs/answered/economy.md; Skyy's popup answer to "...How do we
fix it?" -> "Patch it on our side (Recommended)"). DynamicSeasons 7.0.4 (BlueOrbit, a pack mod; never edited) patches 13 vanilla crop items
(Wheat, Carrot, Potato, Lettuce, Corn, Onion, Rice, Tomato, Turnip, Aubergine, Cauliflower, Chilli, Pumpkin), Plant_Fruit_Apple and its
own Sugarcane / Grapes with a ResourceTypes entry {"Id": "Compost_Soft"} that no pack and not vanilla defines -> the server fails to decode
those items ("Asset Compost_Soft of type ...ResourceType doesn't exist!") and drops them: the crops vanish (Goat / Goat_Kid fail with them).
HOW: the jar now carries an asset pack (IncludesAssetPack true) with ONE file of our own:
  Server/Item/ResourceTypes/Compost_Soft.json = {} - the shape of vanilla's own Foods.json (a ResourceType's only field is the optional
  "Icon"; no icon = nothing that a game update could make fail validation, nothing vanilla-derived shipped), + its name line
  Server/Languages/en-US/server.lang: resourceType.Compost_Soft.name = Soft Compost (vanilla key form, e.g. resourceType.Fuel.name).
Build-time checks (the build stops when one fails): vanilla Assets.zip defines no Compost_Soft ResourceType / name (a game that adds one
makes ours a needless override - drop it then); ResourceType still has exactly the fields id / icon (+ engine bookkeeping) and the
"Icon" key; the asset text is valid JSON {}.
Duplicates: AssetStore.DETECT_DUPLICATE_ASSETS is false (static, set in <clinit>) - a second pack that defines Compost_Soft later just
replaces the earlier definition (the same way mods override vanilla assets), no warning, nothing fails. Both say only "a resource type".
No class changes (version text only). Version 0.1.11.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "SkyyEssentials", "build_skyyessentials_0.1.10.py")
dst = os.path.join(ROOT, "SkyyEssentials", "build_skyyessentials_0.1.11.py")
raw = open(src, encoding="utf8", newline="").read()
CR, LF = chr(13), chr(10)
NL = CR + LF if (CR + LF) in raw else LF
s = raw.replace(CR + LF, LF)
REG0 = s.count("registerCommand(")
SYS0 = s.count("registerSystem(")


def rep(old, new):
    global s
    n = s.count(old)
    assert n == 1, "anchor count %d: %s" % (n, old[:120])
    s = s.replace(old, new, 1)


# ================================================================================================ docstring + version
rep("GENERATED by tools/essentials_0_1_10_patch.py from 0.1.9\n(build_skyyessentials_0.1.9.py,",
    "GENERATED by tools/essentials_0_1_11_patch.py from 0.1.10\n(build_skyyessentials_0.1.10.py,")
rep('"""SkyyEssentials 0.1.10 - build script', '"""SkyyEssentials 0.1.11 - build script')
rep("Run:   python build_skyyessentials_0.1.10.py           -> SkyyEssentials/SkyyEssentials-0.1.10.jar",
    "Run:   python build_skyyessentials_0.1.11.py           -> SkyyEssentials/SkyyEssentials-0.1.11.jar")
rep("Check: python test_skyyessentials_0.1.10.py           (bare JVM, -Xverify:all: the 0.1.9 checks + keep inventory through the engine's death systems)",
    "Check: python test_skyyessentials_0.1.11.py           (bare JVM, -Xverify:all: the 0.1.10 checks + the Compost_Soft resource type decoded by the engine's codec)")
DOC = '''
0.1.11 (2026-10-16, CROPS GONE - Skyy: "Patch it on our side (Recommended)"; docs/answered/economy.md):
  The jar ships the ResourceType 'Compost_Soft' (Server/Item/ResourceTypes/Compost_Soft.json = {}, the shape of vanilla Foods.json;
  name "Soft Compost") that DynamicSeasons 7.0.4 names on 13 vanilla crops + Plant_Fruit_Apple but nothing defines - without it the
  server drops those items. IncludesAssetPack true. No class change. A later pack defining the same id simply replaces ours (the
  engine's duplicate detection is off), nothing fails.
'''
rep("\n0.1.10 (2026-10-15, Skyy:", DOC + "\n0.1.10 (2026-10-15, Skyy:")
rep('\nVERSION = "0.1.10"\n', '\nVERSION = "0.1.11"\n')

# ================================================================================================ the asset pack (one resource type)
ASSET = '''
# 0.1.11: THE MISSING 'Compost_Soft' RESOURCE TYPE (2026-10-16 CROPS GONE; Skyy: "Patch it on our side (Recommended)"). DynamicSeasons
# 7.0.4 tags 13 vanilla crops + Plant_Fruit_Apple with ResourceTypes {"Id": "Compost_Soft"}, which nothing defines, so the server drops
# those items. Ours: {} (vanilla Foods.json's shape - the type's only field "Icon" is optional; no icon = no Common asset to validate,
# nothing vanilla-derived shipped) + its name line in the vanilla key form (resourceType.<Id>.name).
import json as _cpj, zipfile as _cpz
CP_ID = "Compost_Soft"
CP_JSON = "{}\\n"
CP_LANG = "resourceType.%s.name = Soft Compost\\n" % CP_ID
assert _cpj.loads(CP_JSON) == {}
_cp_rt = pool.get("com.hypixel.hytale.server.core.asset.type.item.config.ResourceType")
_cp_f = sorted(str(f.getName()) for f in _cp_rt.getDeclaredFields())
if _cp_f != sorted(["CODEC", "VALIDATOR_CACHE", "ASSET_STORE", "data", "id", "icon", "cachedPacket"]):
    raise SystemExit("0.1.11 Compost_Soft: ResourceType's fields changed (%s) - check the asset shape against vanilla" % _cp_f)
_cp_az = os.path.join(B.HYTALE, "install", "release", "package", "game", "latest", "Assets.zip")
if os.path.isfile(_cp_az):
    with _cpz.ZipFile(_cp_az) as _z:
        _names = set(_z.namelist())
        if "Server/Item/ResourceTypes/Foods.json" not in _names or _cpj.loads(_z.read("Server/Item/ResourceTypes/Foods.json").decode("utf-8-sig")) != {}:
            raise SystemExit("0.1.11 Compost_Soft: vanilla Foods.json is no longer an icon-less {} resource type - re-check the shape")
        if [n for n in _names if n.lower() == ("server/item/resourcetypes/%s.json" % CP_ID).lower()]:
            raise SystemExit("0.1.11 Compost_Soft: vanilla now defines %s itself - drop ours (it would only override vanilla's)" % CP_ID)
        if ("resourceType.%s.name" % CP_ID) in _z.read("Server/Languages/en-US/server.lang").decode("utf-8-sig"):
            raise SystemExit("0.1.11 Compost_Soft: vanilla's server.lang already names %s - drop our line" % CP_ID)
    print("Compost_Soft resource type: vanilla defines none; shape = vanilla Foods.json ({}); ResourceType fields unchanged")
else:
    print("Compost_Soft resource type: Assets.zip not found - vanilla checks skipped")
CP_FILES = {"Server/Item/ResourceTypes/%s.json" % CP_ID: CP_JSON, "Server/Languages/en-US/server.lang": CP_LANG}
'''
rep('''m["IncludesAssetPack"] = False
B.assemble(jar, m, OUT)''', ASSET + '''m["IncludesAssetPack"] = True       # 0.1.11: the Compost_Soft resource type + its name line
B.assemble(jar, m, OUT, CP_FILES)''')
rep('''keep inventory on death (on by default, every world), ''',
    '''keep inventory on death (on by default, every world), the Compost_Soft resource type DynamicSeasons' crops name (so they load), ''')

# ================================================================================================ checks on the generated text
code = s
assert code.count("registerCommand(") == REG0 and code.count("registerSystem(") == SYS0
assert code.count('m["IncludesAssetPack"] = True') == 1 and 'IncludesAssetPack"] = False' not in code
assert "B.assemble(jar, m, OUT, CP_FILES)" in code
assert "B.deploy(" not in code and "enable_in_world(" not in code

open(dst, "w", encoding="utf8", newline="").write(s.replace(LF, NL))
print("wrote", dst, "(line endings %s)" % ("CRLF" if NL == CR + LF else "LF"))
