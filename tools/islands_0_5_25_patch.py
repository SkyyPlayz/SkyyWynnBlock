def archi_encode(L, pal):
    """the 8-char runs of s3_encode (palette index, x + 64, y, z + 64, length <= 63) over the archipelago's shared palette"""
    runs = []
    for k in sorted(L, key=lambda q: (q[1], q[2], q[0])):
        x, y, z = k
        b = L[k]
        r = runs[-1] if runs else None
        if r and r[1] == y and r[2] == z and r[3] == b and r[0] + r[4] == x and r[4] < 63:
            r[4] += 1
        else:
            runs.append([x, y, z, b, 1])

    def d2(v):
        assert 0 <= v < 4096, v
        return S3_ALPHA[v >> 6] + S3_ALPHA[v & 63]
    return "".join(S3_ALPHA[pal.index(b)] + d2(x + S3_OFF) + d2(y) + d2(z + S3_OFF) + S3_ALPHA[n] for x, y, z, b, n in runs), len(runs)


