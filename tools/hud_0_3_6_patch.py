"""Derive SkyyHud/build_skyyhud_0.3.6.py from 0.3.5 (0.3.5 is left untouched; line endings preserved).
0.3.6: every /skyyhud form usable by ordinary players (hytale:Adventurer permission group on the root and every subcommand)
and the documented positional forms made real with subcommands (export | import <code> | reset | preview |
profile list | profile save|load|delete <name>). Layout codes switch from "," to ":" between fields because the engine
tokenizer turns commas into list syntax (more than 10 items = parse error before any command runs). See the new docstring.
Review fix (same 0.3.6): the legacy flag form --action profile --code "save x" gets its surrounding quotes stripped in
HudCmd.act (a quoted flag value keeps its quotes). To regenerate, delete SkyyHud/build_skyyhud_0.3.6.py first.
"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "SkyyHud", "build_skyyhud_0.3.5.py")
dst = os.path.join(ROOT, "SkyyHud", "build_skyyhud_0.3.6.py")
raw = open(src, encoding="utf8", newline="").read()
CR = chr(13)
LF = chr(10)
NL = CR + LF if (CR + LF) in raw else LF
s = raw.replace(CR + LF, LF)


def rep(old, new, count=1):
    global s
    n = s.count(old)
    assert n == count, "anchor count %d != %d: %s" % (n, count, old[:90])
    s = s.replace(old, new)


def between(start_marker, end_marker, new):
    """Replace s[start_marker .. end_marker) (end marker kept)."""
    global s
    assert s.count(start_marker) == 1, "start marker not unique: " + start_marker[:90]
    a = s.index(start_marker)
    b = s.index(end_marker, a)
    s = s[:a] + new + s[b:]


