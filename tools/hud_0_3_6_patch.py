def hud_sub(cls, name, desc, ctor_extra, body, arg_field=None):
    """One player subcommand: plugin field, (name, desc) constructor with the Adventurer group, execute -> body."""
    cls.addField(CtField.make(f"public {PKG}.SkyyHudPlugin plugin;", cls))
    if arg_field:
        cls.addField(CtField.make(f"public {RA} {arg_field};", cls))
    cls.addConstructor(CtNewConstructor.make(f"""
public {cls.getSimpleName()}({PKG}.SkyyHudPlugin p) {{
  super("{name}", "{desc}");
  this.plugin = p;
{ctor_extra}
  {ADV}
}}""", cls))
    cls.addMethod(CtNewMethod.make(f"""
protected void execute({CTX} ctx, {ST} store, {REF} ref, {PR} pr, {WLD} world) {{
  try {{
{body}
  }} catch (Throwable t) {{
    pr.sendMessage({MSG}.raw("[SkyyHud] error: " + t));
  }}
}}""", cls))


