# ---- the version texts: a class-file constant-pool rewrite of CONSTANT_Utf8 entries (same rules the 0.1.21 script's VERSION fills)
def cp_rewrite(b, fn):
    """b = class bytes; fn(str) -> str for every CONSTANT_Utf8 entry; returns (new bytes, changed count)."""
    n = struct.unpack(">H", b[8:10])[0]
    out, i, k, ch = [b[:10]], 10, 1, 0
    while k < n:
        t = b[i]
        if t == 1:
            ln = struct.unpack(">H", b[i + 1:i + 3])[0]
            raw = b[i + 3:i + 3 + ln]
            u = raw.decode("utf8", "surrogatepass") if b"\xc0\x80" not in raw and b"\xed" not in raw else None
            v = fn(u) if u is not None else None
            if v is not None and v != u:
                enc = v.encode("utf8")
                assert len(enc) < 65536
                out.append(b"\x01" + struct.pack(">H", len(enc)) + enc)
                ch += 1
            else:
                out.append(b[i:i + 3 + ln])
            i += 3 + ln
        else:
            size = {3: 5, 4: 5, 5: 9, 6: 9, 7: 3, 8: 3, 16: 3, 19: 3, 20: 3, 9: 5, 10: 5, 11: 5, 12: 5, 17: 5, 18: 5, 15: 4}[t]
            out.append(b[i:i + size])
            i += size
            if t in (5, 6):
                k += 1
        k += 1
    out.append(b[i:])
    return b"".join(out), ch


