"""Derive SkyyHud/build_skyyhud_0.3.22.py from the generated 0.3.21 (the SET pin; 0.3.21 is left untouched; line endings preserved).
Run:  python tools/hud_0_3_22_patch.py   then   python SkyyHud/build_skyyhud_0.3.22.py   (never --deploy)
Harness: python SkyyHud/test_skyyhud_0.3.22.py [--dir <scratch>] [--keep]

0.3.22 = PLAYERS ROUTE THEIR OWN MESSAGES + the "Abilities" message type. Skyy 2026-10-12 (docs/answered/ui.md, CHAT OVERFLOW): "figure
out ways to reduce the chat overflow while still giving players the info they need."
  1. The per-player Chat / Feed / Off switches (msg.<kind> shown or not + msg.<kind>.feed feed or chat, registered through SkyyMenu's
     settings:fn:register) are registered WITHOUT a permission node (7th element null = every player; SkyyMenu 0.3.3+ contract). 0.3.20 /
     0.3.21 registered them with the node skyyhud.messages "until the sender mods use msgroute" - SkyySkills 0.4.34, SkyyClasses 0.1.20 and
     SkyyCollections 0.2.12 now do, so every player gets their own rows. Choices stay where they always were (SkyyMenu's per-player
     settings files, settings:fn:set / get); msgroute:fn:get reads them exactly as before.
     The SERVER defaults stay admin-only: Server Setup -> HUD -> Messages (the config kit rows, node skyyhud.admin) - unchanged.
  2. New message kind "ability" (Server Setup label "Ability casts and results", server default CHAT for now), APPENDED to MSG_KINDS:
     a Server Setup row hud.msg.ability, config line msg.ability=chat, FeedCfg.R_ABILITY, FeedCfg.route("ability"), the two player
     switches msg.ability / msg.ability.feed. A sender asks it the usual way (tools/skyyroute.py MsgRoute.route(u, "ability")) - a later
     round moves the ability cast / result lines ("Meteor! -10 Mana...") off chat; no sender changes here.
  3. Unchanged: widgets, layouts, the feed, commands, permissions of commands, the admin rows (one more), the config file (one more line,
     a missing line = its default).
SETTINGS PAGE FIT: SkyyMenu's /settings shows 8 rows per tab page (fixed height; Prev / Next pages), so 22 rows instead of 20 only add
  rows to the page count - the page height never changes. SkyyMenu 0.3.20 has no "messages" tab: the unknown category lands on the
  General tab (SetReg.catIndex), after General's own rows. Server Setup -> HUD -> Messages: 11 rows (the kit pages 7 rows per view).
ROLLBACK: 0.3.22 -> 0.3.21 is safe: 0.3.21 ignores msg.ability; the stored msg.ability* choices stay in the players' SkyyMenu files and
  0.3.21 hides the rows again from non-holders (their choices are kept, just not shown).
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "SkyyHud", "build_skyyhud_0.3.21.py")
dst = os.path.join(ROOT, "SkyyHud", "build_skyyhud_0.3.22.py")
raw = open(src, encoding="utf8", newline="").read()
CR = chr(13)
LF = chr(10)
NL = CR + LF if (CR + LF) in raw else LF
s = raw.replace(CR + LF, LF)
OLD = s
assert 'VERSION = "0.3.21"' in s and s.startswith('"""SkyyHud 0.3.21 - build script')
CHANGES = []


def rep(old, new):
    global s
    n = s.count(old)
    assert n == 1, "anchor count %d: %s" % (n, old[:160])
    s = s.replace(old, new, 1)
    CHANGES.append((new, old))


# ---------------- docstring + version ----------------
rep('''"""SkyyHud 0.3.21 - build script (javassist via jpype).
Run:   python build_skyyhud_0.3.21.py            -> SkyyHud/SkyyHud-0.3.21.jar
       (deploys only through tools/deploy_set.py - never pass --deploy here)
''', '''"""SkyyHud 0.3.22 - build script (javassist via jpype).
Run:   python build_skyyhud_0.3.22.py            -> SkyyHud/SkyyHud-0.3.22.jar
       (deploys only through tools/deploy_set.py - never pass --deploy here)
0.3.22 (generated by tools/hud_0_3_22_patch.py from 0.3.21): every player routes their OWN messages - the msg.<kind> / msg.<kind>.feed
  switches are registered without a permission node (was skyyhud.messages = ops only); the server defaults stay in Server Setup -> HUD ->
  Messages (admins). New message kind "ability" (Ability casts and results, server default Chat) for a later sender round.
''')
rep('VERSION = "0.3.21"\n', 'VERSION = "0.3.22"\n')

# ---------------- the new kind + no node ----------------
rep('''    ('petxp', 'R_PETXP', 'Pet and guild XP', 'feed', 'Pet and guild XP: in the feed (off = chat)', 'On = a card in the feed above the chat. Off = a line in chat.'),
]
''', '''    ('petxp', 'R_PETXP', 'Pet and guild XP', 'feed', 'Pet and guild XP: in the feed (off = chat)', 'On = a card in the feed above the chat. Off = a line in chat.'),
    # 0.3.22: ability cast / result lines ("Meteor! -10 Mana ..."); Chat until a sender round moves them (tools/skyyroute.py "ability")
    ('ability', 'R_ABILITY', 'Ability casts and results', 'chat', 'Ability casts: in the feed (off = chat)', 'On = a card in the feed above the chat. Off = a line in chat.'),
]
''')
rep('''MSG_NODE = "skyyhud.messages"     # DECISION: the switches are shown to holders only (ops via "*") until the sender mods use msgroute
''', '''MSG_NODE = None     # 0.3.22: every player sees + sets their own switches (0.3.20-0.3.21: "skyyhud.messages" until the senders used msgroute)
''')
rep('''assert len(MSG_SHOW_HELP) <= 100 and len(MSG_KINDS) == 10
''', '''assert len(MSG_SHOW_HELP) <= 100 and len(MSG_KINDS) == 11 and MSG_KINDS[-1][:4] == ('ability', 'R_ABILITY', 'Ability casts and results', 'chat')
''')

# ---------------- FeedCfg ----------------
rep('''    "public static volatile String R_PETXP = \\"feed\\";",
           "public static final String NODE = \\"%s\\";" % MSG_NODE,
''', '''    "public static volatile String R_PETXP = \\"feed\\";",
    "public static volatile String R_ABILITY = \\"chat\\";",
           "public static final String NODE = null;",   # 0.3.22: no node = every player (SkyyMenu settings:fn:register 7th element)
''')
rep('''  if (k.equals("petxp")) return norm(R_PETXP, "feed");
  return null;''', '''  if (k.equals("petxp")) return norm(R_PETXP, "feed");
  if (k.equals("ability")) return norm(R_ABILITY, "chat");
  return null;''')
rep('''  R_PETXP = choice(p.getProperty("msg.petxp"), "feed");
''', '''  R_PETXP = choice(p.getProperty("msg.petxp"), "feed");
  R_ABILITY = choice(p.getProperty("msg.ability"), "chat");
''')

# ---------------- self-checks ----------------
assert s.count("skyyhud.messages") == 2 and "MSG_NODE = None" in s, "the old node only in the two history comments"
assert s.count("R_ABILITY") == 5, s.count("R_ABILITY")   # MSG_KINDS + its assert, the field, route(), loadFrom()
assert "KEEP=10" in s and "KEEP=20" not in s
_u = s
for _new, _old in reversed(CHANGES):
    assert _u.count(_new) == 1, "a change is not unique any more: %s" % _new[:80]
    _u = _u.replace(_new, _old, 1)
assert _u == OLD, "the generated script differs from 0.3.21 outside the recorded changes"
compile(s, dst, "exec")
open(dst, "w", encoding="utf8", newline="").write(s.replace(LF, NL))
print("wrote", dst, "(%d lines, %d changes)" % (s.count(LF), len(CHANGES)))
