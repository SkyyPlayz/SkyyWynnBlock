"""tools/mod_db.py - catalogue every mod in Skyy's UserData Mods folder (READ ONLY) into research/Mod-Database.md.

Skyy 2026-10-11: "build a database of mods to pull from / learn from that cover all the areas of modding we are touching" - this is the
local half (what is already installed); the CurseForge half (licences, mods not installed) is added by the survey round.

For each jar / zip: manifest (group, name, version, server version, dependencies), whether it has code, and counts of what it adds by
area (items, NPCs / mounts, blocks, world gen, UI, animations, models, recipes, sounds), plus a few example item ids. Nothing is copied;
only names, counts and ids are written. Run:  python tools/mod_db.py
"""
import json
import os
import re
import sys
import zipfile

MODS = os.path.join(os.environ.get("APPDATA", ""), "Hytale", "UserData", "Mods")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "research", "Mod-Database.md")
AREAS = [  # (column, path regex) - first match wins per file
    ("items", r"^Server/Item/Items/.*\.json$"),
    ("recipes", r"^Server/(Item/Recipes|Recipes)/"),
    ("npc", r"^Server/NPC/"),
    ("worldgen", r"^Server/(World|WorldGen|Environments|Prefabs)/|^Server/.*Prefab"),
    ("ui", r"^Common/UI/|\.ui$"),
    ("anim", r"\.blockyanim$|^Server/Item/Animations/"),
    ("models", r"\.blockymodel$"),
    ("blocks", r"^Common/Blocks/|^Server/Item/Block"),
    ("sounds", r"\.ogg$|^Server/Audio/"),
]
TAGS = [  # (tag, regex over all paths) - what areas the mod touches, for the "covers" column
    ("mount", r"(?i)mount|saddle|horse|dragon"), ("pet", r"(?i)\bpet|_pet|pets/"), ("weapon", r"(?i)Weapon_"),
    ("armor", r"(?i)Armor_"), ("tool", r"(?i)Tool_"), ("structure", r"(?i)prefab|structure|dungeon"),
    ("biome", r"(?i)biome|zone\d"), ("farming", r"(?i)crop|farm|seed|totem"), ("magic", r"(?i)spell|mana|staff|wand"),
    ("ui", r"(?i)\.ui$|/UI/"), ("animation", r"(?i)\.blockyanim$"), ("quest", r"(?i)quest|dialog"),
]


def scan(path):
    z = zipfile.ZipFile(path)
    names = z.namelist()
    try:
        m = json.loads(z.read("manifest.json").decode("utf-8-sig"))
    except Exception:
        m = {}
    counts = {a: 0 for a, _ in AREAS}
    for n in names:
        for a, rx in AREAS:
            if re.search(rx, n):
                counts[a] += 1
                break
    joined = "\n".join(names)
    tags = [t for t, rx in TAGS if re.search(rx, joined)]
    items = sorted(os.path.splitext(os.path.basename(n))[0] for n in names if re.search(AREAS[0][1], n))
    deps = sorted((m.get("Dependencies") or {}).keys()) + ["(opt) " + k for k in sorted((m.get("OptionalDependencies") or {}).keys())]
    return {"file": os.path.basename(path), "group": m.get("Group", ""), "name": m.get("Name", ""), "ver": m.get("Version", ""),
            "server": m.get("ServerVersion", ""), "code": sum(n.endswith(".class") for n in names), "counts": counts,
            "tags": tags, "items": items, "deps": deps}


def main():
    if not os.path.isdir(MODS):
        sys.exit("no Mods folder at " + MODS)
    rows = []
    for f in sorted(os.listdir(MODS), key=str.lower):
        p = os.path.join(MODS, f)
        if os.path.isfile(p) and f.lower().endswith((".jar", ".zip")):
            try:
                rows.append(scan(p))
            except zipfile.BadZipFile:
                rows.append({"file": f, "bad": True})
    cols = [a for a, _ in AREAS]
    out = ["# Mod database - installed mods (generated)", "",
           "Generated by `python tools/mod_db.py` from Skyy's UserData Mods folder (read only; nothing copied - names, counts, ids).",
           "Licences + mods not installed: added by the CurseForge survey (PROJECT-RULES 2: check existing mods first, no duplicates).",
           "`code` = .class files (0 = an asset-only pack). Skyy* = our own mods.", "",
           "| Mod | Key (Group:Name) | Ver | Server | code | " + " | ".join(cols) + " | touches | example items |",
           "|---|---|---|---|---|" + "---|" * len(cols) + "---|---|"]
    for r in rows:
        if r.get("bad"):
            out.append("| %s | (not a valid zip) |" % r["file"])
            continue
        ex = ", ".join(r["items"][:4]) + (" (+%d)" % (len(r["items"]) - 4) if len(r["items"]) > 4 else "")
        out.append("| %s | %s:%s | %s | %s | %d | %s | %s | %s |" % (
            r["file"].replace("|", "/"), r["group"], r["name"], r["ver"], str(r["server"]).replace("|", "/"), r["code"],
            " | ".join(str(r["counts"][c]) for c in cols), ", ".join(r["tags"]), ex.replace("|", "/")))
    out += ["", "%d mods scanned." % len(rows), ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print("wrote", OUT, len(rows), "mods")


if __name__ == "__main__":
    main()
