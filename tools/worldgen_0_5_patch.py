# ================================================================= helpers
def load(path):
    with open(path, "rb") as f:
        raw = f.read()
    nl = "\r\n" if b"\r\n" in raw else "\n"
    return raw.decode("utf-8").replace("\r\n", "\n"), nl


s = ""


def rep(old, new, count=1):
    global s
    n = s.count(old)
    if n != count:
        raise SystemExit("patch: expected %d match(es), found %d for:\n%s" % (count, n, old[:400]))
    s = s.replace(old, new)


def cut(start, end):
    """remove s[start .. end) (both markers must be unique; end marker kept)"""
    global s
    a, b = s.count(start), s.count(end)
    if a != 1 or b != 1:
        raise SystemExit("patch: cut markers %d / %d:\n%s\n%s" % (a, b, start[:200], end[:200]))
    i, j = s.index(start), s.index(end)
    assert i < j
    s = s[:i] + s[j:]


