def zone_island(S, vox, z, W, H, seed):
    zone_tex(S, vox, z)
    bl, top = island_blocks(z, W, H, seed)
    ox, oy = isl_origin(vox, W, H)
    shade = isl_shade(top)
    if z == 5:
        base_shade = shade

        def shade(b, face, base):   # the lava cracks + pools glow (they are lit from inside)
            return (112 if face == "T" else 100) if bl[b] in ("z5a", "z5l") else base_shade(b, face, base)
    P, _ = vox.render(bl, shade, origin=(ox, oy), size=(W * SS, H * SS))
