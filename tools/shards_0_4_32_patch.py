def lava_glow(cr, lava):
    # the crack texture with its reddish veins lit: each vein pixel takes the lava texture's colour, by how red it is
    o = Pic(cr.w, cr.h)
    o.px = bytearray(cr.px)
    for i in range(0, len(o.px), 4):
        r, g, b = cr.px[i], cr.px[i + 1], cr.px[i + 2]
        red = (r - (g + b) / 2.0) / 40.0
        if red > 0.25:
            t = min(1.0, red)
            j = i % (lava.w * lava.h * 4)
            for c in range(3):
                o.px[i + c] = _c(r * (1 - t) + lava.px[j + c] * t)
    return o


