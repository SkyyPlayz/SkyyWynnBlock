def with_fruit(p, fruit, seed, n=9):
    f = fit(crop_alpha(fruit), 15, 15, up=True)
    o = Pic(p.w, p.h)
    o.px = bytearray(p.px)
    top = int(p.h * 0.62)
    placed = 0
    for q in range(200):
        if placed >= n:
            break
        x = int(h01(q, 1, seed) * (p.w - f.w))
        y = int(h01(q, 2, seed) * (top - f.h))
        i = ((y + f.h // 2) * p.w + x + f.w // 2) * 4
        if p.px[i + 3] < 250:
            continue
        o.paste(f, x, y)
        placed += 1
    return o


def rim(p, col=(255, 242, 212), a1=190, a2=80):
    # fix2: a soft light outline (2 px) round a picture's shape, so a dark monster reads on dark ground (Zone 4 / 5)
    o = Pic(p.w + 4, p.h + 4)
    al = p.px[3::4]

    def solid_at(x, y):
        return 0 <= x < p.w and 0 <= y < p.h and al[y * p.w + x] >= 128
    for y in range(-2, p.h + 2):
        for x in range(-2, p.w + 2):
            if solid_at(x, y):
                continue
            n1 = solid_at(x - 1, y) or solid_at(x + 1, y) or solid_at(x, y - 1) or solid_at(x, y + 1)
            if n1:
                o.over(x + 2, y + 2, col[0], col[1], col[2], a1)
            elif solid_at(x - 2, y) or solid_at(x + 2, y) or solid_at(x, y - 2) or solid_at(x, y + 2) or solid_at(x - 1, y - 1) or                     solid_at(x + 1, y - 1) or solid_at(x - 1, y + 1) or solid_at(x + 1, y + 1):
                o.over(x + 2, y + 2, col[0], col[1], col[2], a2)
    o.paste(p, 2, 2)
    return o


def card(ic, W=110, H=140, mh=118, sh=0.42, lit=False):
    # a picture standing on its spot: fit, feet on a soft shadow near the bottom; lit = a monster: top light + a light rim
    p = Pic(W, H)
    f = fit(ic, W - 10 if lit else W - 6, mh - 4 if lit else mh)
    if lit:
        f = rim(light(f, top=1.12, bot=0.94))
    shadow(p, W / 2.0, H - 12, max(8, f.w * sh), 6, 120)
    p.paste(f, (W - f.w) // 2, H - 12 - f.h + 5)
    return p


