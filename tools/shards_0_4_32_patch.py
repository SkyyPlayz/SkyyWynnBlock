def bbox(p, thr=8):
    x0, y0, x1, y1 = p.w, p.h, -1, -1
    for y in range(p.h):
        row = p.px[y * p.w * 4 + 3:(y + 1) * p.w * 4:4]
        xs = [x for x, a in enumerate(row) if a > thr]
