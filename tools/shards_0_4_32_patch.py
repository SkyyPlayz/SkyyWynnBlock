def opaque32(img, n=32):
    # the most opaque n x n window of a foliage texture (leaf textures have holes), made fully opaque
    if img.w == n and img.h == n:
        o = Pic(n, n)
        o.px = bytearray(img.px)
    else:
        best = None
        for y0 in range(0, img.h - n + 1, 4):
            for x0 in range(0, img.w - n + 1, 4):
                cnt = 0
                for y in range(y0, y0 + n, 2):
                    for x in range(x0, x0 + n, 2):
                        if img.px[(y * img.w + x) * 4 + 3] < 250:
                            cnt += 1
                if best is None or cnt < best[0]:
                    best = (cnt, x0, y0)
        _, x0, y0 = best
        o = cut(img, x0, y0, x0 + n, y0 + n)
    # holes take the average leaf colour
    r = g = b = k = 0
    for i in range(0, len(o.px), 4):
        if o.px[i + 3] > 128:
            r += o.px[i]; g += o.px[i + 1]; b += o.px[i + 2]; k += 1
    k = max(1, k)
    av = (r // k, g // k, b // k)
    for i in range(0, len(o.px), 4):
        if o.px[i + 3] <= 128:
            o.px[i], o.px[i + 1], o.px[i + 2] = _c(av[0] * 0.8), _c(av[1] * 0.8), _c(av[2] * 0.8)
        o.px[i + 3] = 255
    return o


