def _ball(bl, cx, cy, ck, rx, rz, seed, key="leaves", holes=0.08):
    R = int(rx) + 1
    Z = int(rz) + 1
    for di in range(-R, R + 1):
        for dj in range(-R, R + 1):
            for dk in range(-Z, Z + 1):
                if (di * di + dj * dj) / (rx * rx + 0.6) + (dk * dk) / (rz * rz + 0.6) <= 1.0 and h01(di + cx, dj + cy * 3, dk + seed) > holes:
                    p = (cx + di, cy + dj, ck + dk)
                    if p not in bl:
                        bl[p] = key


