def ore_icon(S, blk, host_icon, col, base_icon):
    # the game's ore block icon; a SkyWynn ore (not in the game) = the vanilla ore of its host rock with the ore chunks recoloured
    if S.has("Common/Icons/ItemsGenerated/%s.png" % blk):
        return S.icon(blk)
    ore, rock = S.icon(base_icon), S.icon(host_icon)
    o = Pic(ore.w, ore.h)
    o.px = bytearray(ore.px)
    for i in range(0, len(o.px), 4):
        if ore.px[i + 3] < 8:
            continue
        d = abs(ore.px[i] - rock.px[i]) + abs(ore.px[i + 1] - rock.px[i + 1]) + abs(ore.px[i + 2] - rock.px[i + 2]) + abs(ore.px[i + 3] - rock.px[i + 3])
        if d > 60:
            l = (ore.px[i] + ore.px[i + 1] + ore.px[i + 2]) / 765.0
            o.px[i], o.px[i + 1], o.px[i + 2] = _c(col[0] * (0.35 + l * 1.1)), _c(col[1] * (0.35 + l * 1.1)), _c(col[2] * (0.35 + l * 1.1))
    return o


