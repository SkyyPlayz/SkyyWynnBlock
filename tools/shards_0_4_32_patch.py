# ------------------------------------------------------------------------------------------------ the voxel renderer (2:1 isometric, painter's order)
class Vox(object):
    # scr(i, j, k) = ((i - j) * A, (i + j) * B - k * H) in SS pixels; one instance per block size, its face sprites cached
    def __init__(self, A, B, H, bevel=()):
        self.A, self.B, self.H = A, B, H
        self.tex = {}
        self.bevel = set(bevel)
        self.cache = {}

    def scr(self, i, j, k):
        return (i - j) * self.A, (i + j) * self.B - k * self.H

    def sprite(self, key, face, shade):
        ck = (key, face, shade)
        if ck in self.cache:
            return self.cache[ck]
        A, B, H = self.A, self.B, self.H
        if face == "T":
            o, du, dv = (0.0, -H), (A, B), (-A, B)
            tk = key + "@top" if (key + "@top") in self.tex else key
        elif face == "R":
            o, du, dv = (0.0, 2 * B - H), (A, -B), (0.0, H)
            tk = key
        else:
            o, du, dv = (-A, B - H), (A, B), (0.0, H)
            tk = key
        t = self.tex[tk]
        det = du[0] * dv[1] - du[1] * dv[0]
        tw, th = t.w, t.h
        e = 0.7 / min(A, H)
        sh = shade / 100.0
        if face == "T":
            mr, mg, mb = sh * 1.05, sh * 1.02, sh * 0.93
        else:
            mr, mg, mb = sh * 0.97, sh * 0.99, sh * 1.05
        bev = key in self.bevel
        rows = []
        tp = t.px
        for y in range(-H - 1, 2 * B + 1):
            run = []
            x0 = None
            for x in range(-A - 1, A + 1):
                r = g = b = 0
                inside = False
                for (sx, sy) in ((0.25, 0.25), (0.75, 0.25), (0.25, 0.75), (0.75, 0.75)):
                    px, py = x + sx - o[0], y + sy - o[1]
                    u = (px * dv[1] - py * dv[0]) / det
                    v = (du[0] * py - du[1] * px) / det
                    if -e <= u <= 1 + e and -e <= v <= 1 + e:
                        inside = True
                    uu, vv = min(max(u, 0.0), 0.9999), min(max(v, 0.0), 0.9999)
                    i = (int(vv * th) * tw + int(uu * tw)) * 4
                    r += tp[i]
                    g += tp[i + 1]
                    b += tp[i + 2]
                if not inside:
                    if x0 is not None:
                        break
                    continue
                if x0 is None:
                    x0 = x
                m = 1.0
                if bev:
                    px, py = x + 0.5 - o[0], y + 0.5 - o[1]
                    u = (px * dv[1] - py * dv[0]) / det
                    v = (du[0] * py - du[1] * px) / det
                    if min(u, v, 1 - u, 1 - v) * min(A, H) < 1.0:
                        m = 0.84 if face != "T" else 1.12
                run += [_c(r / 4.0 * mr * m), _c(g / 4.0 * mg * m), _c(b / 4.0 * mb * m), 255]
            if x0 is not None:
                rows.append((y, x0, bytes(bytearray(run))))
        self.cache[ck] = rows
        return rows

    def render(self, blocks, shade_fn=None, pad=2, solid=None, origin=None, size=None):
        # blocks {(i, j, k): key} -> (Pic at SS scale, (ox, oy) = the screen place of world (0, 0, 0)); a face is drawn when its neighbour
        # is not in `solid` (default: the blocks themselves); origin + size = a fixed canvas (overlays share their island's canvas)
        A, B, H = self.A, self.B, self.H
        sol = blocks if solid is None else solid
        if origin is None:
            xs, ys = [], []
            for (i, j, k) in blocks:
                sx, sy = self.scr(i, j, k)
                xs += [sx - A, sx + A]
                ys += [sy - H, sy + 2 * B]
            ox, oy = -min(xs) + pad, -min(ys) + pad
            ox += ox % 2
            oy += oy % 2
            P = Pic(max(xs) + ox + pad + 2, max(ys) + oy + pad + 2)
        else:
            ox, oy = origin
            P = Pic(size[0], size[1])
        W = P.w
        order = sorted(blocks, key=lambda b: (b[0] + b[1] + b[2], b[2], b[0]))
        for b in order:
            i, j, k = b
            key = blocks[b]
            faces = []
            if (i, j, k + 1) not in sol:
                faces.append("T")
            if (i + 1, j, k) not in sol:
                faces.append("R")
            if (i, j + 1, k) not in sol:
                faces.append("L")
            if not faces:
                continue
            sx, sy = self.scr(i, j, k)
            sx += ox
            sy += oy
            for f in faces:
                base = {"T": 100, "L": 80, "R": 63}[f]
                sh = shade_fn(b, f, base) if shade_fn else base
                for (y, x0, row) in self.sprite(key, f, sh):
                    yy = sy + y
                    if yy < 0 or yy >= P.h:
                        continue
                    xx = sx + x0
                    n = len(row) // 4
                    c0 = 0 if xx >= 0 else -xx
                    c1 = n if xx + n <= W else W - xx
                    if c1 <= c0:
                        continue
                    a = (yy * W + xx + c0) * 4
                    P.px[a:a + (c1 - c0) * 4] = row[c0 * 4:c1 * 4]
        return P, (ox, oy)


def box(d, x0, y0, z0, x1, y1, z1, key):
    for i in range(x0, x1):
        for j in range(y0, y1):
            for k in range(z0, z1):
                d[(i, j, k)] = key


def model_pic(vox, bl, glow_keys=(), shade=None):
    p, o = vox.render(bl, shade_fn=shade or (lambda b, f, base: 100 if bl[b] in glow_keys else base))
    return crop_alpha(down2(p))


