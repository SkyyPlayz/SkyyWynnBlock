def win_check(v, what):
    roots = [mk_ for p_, mk_ in v if p_ is None]
    assert len(roots) == 1, what
    m_ = re.match(r"\\s*Group #\\w+ \\{ Anchor: \\(Width: (\\d+), Height: (\\d+)\\); \\}", SUI.render(roots[0]))
    assert m_ and int(m_.group(1)) <= SUI.MAX_PAGE_W and int(m_.group(2)) <= SUI.MAX_PAGE_H, "%s: the window is bigger than 1600 x 980" % what
    rows, pri, texts = set(), 0, []
    for p_, mk_ in v:
        s_ = SUI.render(mk_)
        rows.update(re.findall(r"Group #(\\w+Tabs) \\{", s_))
        in_tabs = p_ is not None and str(p_).lstrip("#").endswith("Tabs")
        if in_tabs and s_.lstrip().startswith("TextButton"):
            assert "Height: %d" % SUI.SUB_TAB_H in s_, "%s: a tab button is not 32 px: %s" % (what, s_[:90])
        if s_.lstrip().startswith("TextButton") and _WPRI in s_ and not in_tabs:
            pri += 1
        texts += _WTX.findall(s_)
    texts += [str(SUI.render(x[2])) for x in getattr(v, "sets", []) if len(x) > 2 and x[1] == "Text"]
    assert len(rows) <= 1, "%s: %d tab rows %s (a window has one at most)" % (what, len(rows), sorted(rows))
    assert pri <= 1, "%s: %d Primary buttons (one per view)" % (what, pri)
    bad = [t_ for t_ in texts if SUI.MENU_BACK_RE.match(t_) or SUI.MENU_PAGER_RE.match(t_) or t_.strip().lower() in ("previous", "next")]
    assert not bad, "%s: Back / pager text %s" % (what, bad)
    return len(rows)


