class Patch2(G.Patch):
    """G.Patch + sweeps: whole-word text replacements applied AFTER the anchored-change check, on code lines only (not comments, not the
    head docstring). Each sweep asserts its new text did not exist before and how often it applied."""

    def __init__(self, src, dst):
        G.Patch.__init__(self, src, dst)
        self.sweeps = []

    def cut(self, a, b):
        assert self.s.count(a) == 1, "cut start count %d: %s" % (self.s.count(a), a[:120])
        i = self.s.index(a)
        j = self.s.index(b, i)
        assert self.s.count(b) >= 1
        return self.s[i:j + len(b)]

    def sweep(self, old, new):
        self.sweeps.append((old, new))

    def finish(self):
        u = self.s
        for new, old in reversed(self.changes):
            assert u.count(new) == 1, "a change is not unique any more: %s" % new[:100]
            u = u.replace(new, old, 1)
        assert u == self.OLD, "the generated script differs from its source outside the recorded changes"
        LF = chr(10)
        head_end = self.s.index('"""', 3) + 3
        head, body = self.s[:head_end], self.s[head_end:]
        lines = body.split(LF)
        for old, new in self.sweeps:
            n = 0
            for i, ln in enumerate(lines):
                if ln.lstrip().startswith("#") or old not in ln:
                    continue
                n += ln.count(old)
                lines[i] = ln.replace(old, new)
            print("sweep %r -> %r: %d" % (old, new, n))
        self.s = head + LF.join(lines)
        compile(self.s, self.dst, "exec")
        open(self.dst, "w", encoding="utf8", newline="").write(self.s.replace(LF, self.NL) if self.NL != LF else self.s)
        print("wrote", self.dst, "(%d lines; the source had %d; %d changes, %d sweeps)" % (self.s.count(LF), self.OLD.count(LF),
                                                                                        len(self.changes), len(self.sweeps)))


