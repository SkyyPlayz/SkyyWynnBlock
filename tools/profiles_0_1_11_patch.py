def stripe(head, ret, call, first_arg="u"):
    """turn `public static synchronized <ret> <name>(<args>) {` (one M(sto, ...) block) into <name>0 without a monitor, and add the
    wrapper `<name>(<args>)` right after it: the body runs under lockOf(<first_arg>) - one call in the synchronized block (javassist)"""
