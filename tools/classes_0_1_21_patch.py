"""Derive SkyyClasses/build_skyyclasses_0.1.21.py from the generated 0.1.20 (the SET pin; the EDITED lineage: Skyy's edited 0.1.6 ->
classes_0_1_7_patch.py -> ... -> classes_0_1_20_patch.py -> 0.1.20; classes_0_1_6_patch.py is never re-run). 0.1.20 stays untouched; its
line endings are kept.
Run:  python tools/classes_0_1_21_patch.py   then   python SkyyClasses/build_skyyclasses_0.1.21.py   (never --deploy)
Test: python SkyyClasses/test_skyyclasses_0.1.21.py [--dir <scratch>] [--keep]

0.1.21 (2026-10-13) = ABILITY LINES -> FEED (Skyy 2026-10-12, docs/answered/ui.md CHAT OVERFLOW: "figure out ways to reduce the chat
overflow while still giving players the info they need"). SkyyHud 0.3.22 added the message kind "ability" (server default Chat).
  - Every ability CAST / RESULT announcement goes through Abil.say ("Meteor! -10 Mana, -2 Stamina. Ready again in 8 s.", "Meteor hit 3
    enemies ...", zone start / end lines, Guardian Spirit saves). Abil.say now routes kind "ability" through the shared MsgRoute
    (tools/skyyroute.py, already in 0.1.20): chat = the 0.1.20 line word for word; feed = one feed card (kind ability, no icon) with
    Abil.feedText(text) (the line itself when it fits SkyyHud's 48-character card; else shortened: "before armour" dropped, "Stamina" ->
    "Stam", "(...)" asides dropped, the first sentence, then the last ", " / " - " break - e.g. "Meteor! -10 Mana -2 Stam, ready in 8 s.");
    off = nothing. No SkyyHud, a SkyyHud older than 0.3.22 (no "ability" kind = chat) or a refused card = the chat line.
  - The admin switch (abil.castChat) and the player's switch (classes.abilChat) still hide the line completely first, as in 0.1.20.
  - REFUSALS STAY IN CHAT: not enough Mana / Stamina, on cooldown, locked, nobody to heal, usage and error lines go through Abil.refuse /
    Abil.send (never routed), with their fail sound - unchanged. So does the "... broke - you moved" warning.
  No config key, no saved data, no migration, no command. Rolling back to 0.1.20 is safe (ability lines go back to chat).
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "SkyyClasses", "build_skyyclasses_0.1.20.py")
dst = os.path.join(ROOT, "SkyyClasses", "build_skyyclasses_0.1.21.py")
raw = open(src, encoding="utf8", newline="").read()
CR, LF = chr(13), chr(10)
NL = CR + LF if (CR + LF) in raw else LF
s = raw.replace(CR + LF, LF)
OLD = s
assert 'VERSION = "0.1.20"' in s and "GENERATED by tools/classes_0_1_20_patch.py from the generated 0.1.19" in s, \
    "build_skyyclasses_0.1.20.py is not the generated 0.1.20"
assert 'MsgRoute.route(u, "ability")' not in s
REG0 = s.count("registerCommand(")
SYS0 = s.count("registerSystem(")
CHANGES = []


def rep(old, new):
    global s
    n = s.count(old)
    assert n == 1, "anchor count %d: %s" % (n, old[:120])
    s = s.replace(old, new, 1)
    CHANGES.append((new, old))


HEAD = open(__file__, encoding="utf8").read().split('"""')[1]
NOTE = HEAD[HEAD.index("0.1.21 (2026-10-13)"):].rstrip()

# ================================================================================================ docstring, version
rep('''"""SkyyClasses 0.1.20 - build script (javassist via jpype). GENERATED by tools/classes_0_1_20_patch.py from the generated 0.1.19 (the
EDITED lineage: Skyy's edited 0.1.6 -> classes_0_1_7_patch.py -> 0.1.7 -> ... -> classes_0_1_19_patch.py -> 0.1.19) - edit the patch, not
this file; classes_0_1_6_patch.py is never re-run. Wynncraft-style classes for SkyWynn.
''', '''"""SkyyClasses 0.1.21 - build script (javassist via jpype). GENERATED by tools/classes_0_1_21_patch.py from the generated 0.1.20 (the
EDITED lineage: Skyy's edited 0.1.6 -> classes_0_1_7_patch.py -> 0.1.7 -> ... -> classes_0_1_20_patch.py -> 0.1.20) - edit the patch, not
this file; classes_0_1_6_patch.py is never re-run. Wynncraft-style classes for SkyWynn.
''' + NOTE.replace(LF, LF + "  ").replace("  " + LF, LF) + '''
  Notes in tools/classes_0_1_21_patch.py. CHECKED with SkyyClasses/test_skyyclasses_0.1.21.py.
''')
rep('VERSION = "0.1.20"', 'VERSION = "0.1.21"')

# ================================================================================================ Abil.feedText + the routed Abil.say
CARD_MAX = 48       # SkyyHud 0.3.22 FeedPush: cleanText(text, 48)
rep('''M(abil, r"""
public static void say(@PR@ pr, String text) {
  try {
    if (pr == null || !@PKG@.AbilCfg.CAST_CHAT) return;
    if (!@PKG@.ClassCfg.notifyOn(pr.getUuid(), "classes.abilChat")) return;
  } catch (Throwable t) { return; }
  send(pr, text, "#8fe39a");
}""")''', '''# 0.1.21: the feed card text of an ability line - the line itself when it fits SkyyHud's card (%d characters), else shortened step by
# step (each step only while still too long): "before armour" dropped, "Stamina" -> "Stam"; "(...)" asides dropped; the first sentence;
# no closing "."; the last ", " / " - " / ": " break; at last cut + "...".
M(abil, r"""
public static String feedText(String t) {
  if (t == null) return "";
  String s = t.trim();
  int max = %d;
  if (s.length() <= max) return s;
  s = s.replace(" before armour", "").replace(", -", " -").replace(" Stamina. Ready again in ", " Stam, ready in ").replace(" Stamina", " Stam");
  if (s.length() <= max) return s;
  int a = s.indexOf(" (");
  int guard = 0;
  while (a >= 0 && guard < 8) {
    int b = s.indexOf(")", a);
    if (b < 0) break;
    s = s.substring(0, a) + s.substring(b + 1);
    a = s.indexOf(" (");
    guard++;
  }
  if (s.length() <= max) return s;
  int dot = s.indexOf(". ");
  if (dot >= 16) s = s.substring(0, dot + 1);
  if (s.length() <= max) return s;
  if (s.endsWith(".")) s = s.substring(0, s.length() - 1);
  if (s.length() <= max) return s;
  String head = s.substring(0, max);
  int cut = Math.max(head.lastIndexOf(", "), Math.max(head.lastIndexOf(" - "), head.lastIndexOf(": ")));
  if (cut >= 16) return s.substring(0, cut).trim();
  return s.substring(0, max - 3).trim() + "...";
}""")
# 0.1.21 route "ability" (SkyyHud 0.3.22; server default Chat): off = nothing; feed = one card (kind ability, no icon, feedText); chat / no
# SkyyHud / an older SkyyHud (no "ability" kind = chat) / a refused card = the 0.1.20 line word for word. The two switches gate first.
M(abil, r"""
public static void say(@PR@ pr, String text) {
  java.util.UUID u = null;
  try {
    if (pr == null || !@PKG@.AbilCfg.CAST_CHAT) return;
    u = pr.getUuid();
    if (!@PKG@.ClassCfg.notifyOn(u, "classes.abilChat")) return;
  } catch (Throwable t) { return; }
  String r = @PKG@.MsgRoute.route(u, "ability");
  if ("off".equals(r)) { @PKG@.MsgRoute.off(); return; }
  if ("feed".equals(r) && @PKG@.MsgRoute.feed(u, "ability", null, feedText(text), 0L)) return;
  @PKG@.MsgRoute.said("[Classes] " + text);
  send(pr, text, "#8fe39a");
}""")''' % (CARD_MAX, CARD_MAX))
rep('''Priests heal their party and own the Healing Totem (heal lines go to the SkyyHud notification feed when the player picks Feed);''',
    '''Priests heal their party and own the Healing Totem (heal and ability lines go to the SkyyHud notification feed when the player picks Feed);''')

# ================================================================================================ checks on the result
assert s.count("registerCommand(") == REG0 and s.count("registerSystem(") == SYS0, "no new command / system"
assert s.index('pool.makeClass(PKG + ".MsgRoute")') < s.index('abil = pool.makeClass(PKG + ".Abil")') < s.index("public static String feedText(String t)") \
    < s.index('MsgRoute.route(u, "ability")'), "MsgRoute before Abil, feedText before say"
assert s.count('MsgRoute.route(u, "ability")') == 1 and s.count("public static void refuse(@PR@ pr, String text)") == 1
_u = s
for _new, _old in reversed(CHANGES):
    assert _u.count(_new) == 1, "a change is not unique any more: %s" % _new[:80]
    _u = _u.replace(_new, _old, 1)
assert _u == OLD, "the generated script differs from 0.1.20 outside the recorded changes"
compile(s, dst, "exec")
open(dst, "w", encoding="utf8", newline="").write(s.replace(LF, NL))
print("wrote", os.path.relpath(dst, ROOT), "(%d lines; 0.1.20 had %d; %d anchored changes)" % (s.count(LF), OLD.count(LF), len(CHANGES)))
