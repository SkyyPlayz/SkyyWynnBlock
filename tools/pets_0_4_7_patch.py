def _resolve(rules, rid):
    """the Python twin of SkyySkills SkillCfg.resolve: exact wins, then the longest prefix, then a longer suffix (ties: prefix)"""
    for k, i, s, x in rules:
        if k == 0 and i == rid:
            return (k, i, s, x)
    best, bl = None, -1
    for k, i, s, x in rules:
        if k == 1 and len(i) > bl and rid.startswith(i):
            best, bl = (k, i, s, x), len(i)
    for k, i, s, x in rules:
        if k == 2 and len(i) > bl and rid.endswith(i):
            best, bl = (k, i, s, x), len(i)
    return best


