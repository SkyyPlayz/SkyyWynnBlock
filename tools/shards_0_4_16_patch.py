def _rep_each(old, new):
    # every window (the line holding old + the lines after it until unique) is fixed on the text BEFORE any of these changes, so the
    # changed windows stay unique too (two identical lines get two different windows)
    S = P.s
    assert new not in S, new
    wins, i = [], S.find(old)
    while i >= 0:
        a = S.rfind(chr(10), 0, i) + 1
        b = S.index(chr(10), i + len(old))
        while S.count(S[a:b]) != 1:
            b = S.index(chr(10), b + 1)
        assert not wins or a >= wins[-1][1], "windows overlap"
        wins.append((a, b))
        i = S.find(old, i + len(old))
    for a, b in wins:
        w = S[a:b]
        P.rep(w, w.replace(old, new))
    return sum(S[a:b].count(old) for a, b in wins)
