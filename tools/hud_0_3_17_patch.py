"""Derive SkyyHud/build_skyyhud_0.3.17.py from the generated 0.3.16 (the SET pin; 0.3.16 is left untouched; line endings preserved).
0.3.17 = a small client-log fix round (docs/log/2026-10.md 2026-10-08 LOG SCAN; Skyy: "the last play has 56+ critical errors dev mode
found, so make sure to check the logs to fix things."):
  (1) the client warned "Mod Skyy:0.3.16 SkyyHud has an icon.png with wrong dimensions (64x64, expected 256x256)". The client reads a
      mod's ROOT `icon-256.png` as its icon (HytaleClient.exe strings: "icon-256.png" next to "Mod {0} has an icon.png with wrong
      dimensions ({1}x{2}, expected {3}x{3})" / "has an invalid icon.png (not a valid PNG)"); SkyyHud 0.2.1 shipped a flat 64 x 64 green
      placeholder there. 0.3.17 ships a 256 x 256 original icon drawn by SkyyHud/make_icon.py (deterministic, no vanilla pixels) and the
      build REFUSES an icon that is not a valid 256 x 256 PNG (make_icon.check_icon). Same jar path, same file name.
  (2) "Tried to update custom page while no custom page was open" (2x): NOT SkyyHud. SkyyHud's three pages (EditorPage, SettingsPage,
      WidgetsPage) send page updates ONLY through the engine's CustomUIPage.rebuild() inside handleDataEvent (no timer, no tick, no
      sendUpdate anywhere in the script); the engine's PageManager.handleEvent hands a Data event to the page only while it is the
      server's open page (bytecode: customPage null -> AnchorActionModule instead). The HUD's own 1 s tick updates the HUD (CustomHud
      packet, a different client message), never a page. No code change for it (a guard would test what the engine already tests).
Everything else: byte-identical code; only the version strings change.
Harness: python SkyyHud/test_skyyhud_0.3.17.py (icon checks + negative controls, the 0.3.16 harness re-run on the 0.3.17 jar, class
compare 0.3.16 vs 0.3.17, engine asset validators on the icon, start twice on a scratch copy of the live data).
To regenerate, delete SkyyHud/build_skyyhud_0.3.17.py first (the script refuses to overwrite it).
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "SkyyHud", "build_skyyhud_0.3.16.py")
dst = os.path.join(ROOT, "SkyyHud", "build_skyyhud_0.3.17.py")
assert not os.path.exists(dst), "refusing to overwrite " + dst
raw = open(src, encoding="utf8", newline="").read()
CR = chr(13)
LF = chr(10)
NL = CR + LF if (CR + LF) in raw else LF
s = raw.replace(CR + LF, LF)


def rep(old, new, count=1):
    global s
    n = s.count(old)
    assert n == count, "anchor count %d != %d: %s" % (n, count, old[:90])
    s = s.replace(old, new)


# ---- header + version
rep('''"""SkyyHud 0.3.16 - build script (javassist via jpype).
Run:   python build_skyyhud_0.3.16.py            -> SkyyHud/SkyyHud-0.3.16.jar
       (deploys only through tools/deploy_set.py - never pass --deploy here)
''', '''"""SkyyHud 0.3.17 - build script (javassist via jpype).
Run:   python build_skyyhud_0.3.17.py            -> SkyyHud/SkyyHud-0.3.17.jar
       (deploys only through tools/deploy_set.py - never pass --deploy here)
0.3.17 (generated by tools/hud_0_3_17_patch.py from 0.3.16): the mod icon. The client reads the jar's root icon-256.png and wants it
  256 x 256 (client log 2026-10-08: "has an icon.png with wrong dimensions (64x64, expected 256x256)"); SkyyHud/make_icon.py draws an
  original 256 x 256 icon and this script refuses to build with an icon that is not a valid 256 x 256 PNG. No code change (the
  "Tried to update custom page" client warning is not SkyyHud's: tools/hud_0_3_17_patch.py's docstring).
''')
rep('VERSION = "0.3.16"', 'VERSION = "0.3.17"')

# ---- the icon: a valid 256 x 256 PNG or no build
rep('''png_root = open(os.path.join(HERE, "icon-256.png"), "rb").read()
''', '''png_root = open(os.path.join(HERE, "icon-256.png"), "rb").read()
# 0.3.17: the client reads this root icon-256.png as the mod's icon and wants 256 x 256 (it warned on the old 64 x 64 placeholder)
sys.path.insert(0, HERE)
import make_icon as _MI
_icon_err = _MI.check_icon(png_root, 256)
assert _icon_err is None, "SkyyHud/icon-256.png: " + _icon_err + " - run python SkyyHud/make_icon.py"
print("icon-256.png: 256 x 256 PNG ok (%d bytes)" % len(png_root))
''')

out = s.replace(LF, NL)
open(dst, "w", encoding="utf8", newline="").write(out)
print("wrote", dst, "(%d lines)" % out.count(LF))
