def s3_noise(x, y, z=0):
    n = ((x * 73856093) ^ (y * 19349663) ^ (z * 83492791)) & 0xffffffff
    n = ((n ^ (n >> 13)) * 1274126177) & 0xffffffff
    return ((n ^ (n >> 16)) & 0xffff) / 65536.0


def s3_vnoise(x, z, sc, k):
    """smooth value noise (bilinear over a lattice sc blocks apart) in [0, 1): the hill's lumps"""
    fx, fz = x / sc, z / sc
    ix, iz = int(_s3m.floor(fx)), int(_s3m.floor(fz))
    ux, uz = fx - ix, fz - iz
    ux, uz = ux * ux * (3 - 2 * ux), uz * uz * (3 - 2 * uz)
    a, b = s3_noise(ix, iz, k), s3_noise(ix + 1, iz, k)
    c, d = s3_noise(ix, iz + 1, k), s3_noise(ix + 1, iz + 1, k)
    return (a + (b - a) * ux) + ((c + (d - c) * ux) - (a + (b - a) * ux)) * uz


