"""Derive SkyyBank/build_skyybank_0.1.10.py from the LIVE 0.1.9 (build_skyybank_0.1.9.py = the tools/deploy_set.py SET pin; itself
generated by tools/bank_0_1_9_patch.py - never re-run that one, never edit either generated script).
Run:  python tools/bank_0_1_10_patch.py   then   python SkyyBank/build_skyybank_0.1.10.py   (never --deploy: coordinated deploy)
      then  python SkyyBank/test_skyybank_0.1.10.py [--keep]

0.1.10 (2026-10-13) = THE PROFILE NAME LINE (Skyy 2026-10-13: "have the name show (Class) (profile name."). SkyyProfiles 0.1.12 made
bridge profile:name:<uuid> the display text "<Class> <name>" (e.g. "Priest Banana") and added profile:pname:<uuid> = the bare name
(tools/PROFILES-CONTRACT.md). 0.1.9's page line appended " (" + profile:class + ")" after profile:name, so with 0.1.12 the Bank showed
the class twice ("Profile Priest Banana (Priest)"). Now BankPage.subText:
  - profile:pname:<uuid> present (SkyyProfiles 0.1.12+): profile:name is shown as it is -> "Profile Priest Banana";
  - profile:pname absent (an older SkyyProfiles: profile:name = the bare name): the old " (Class)" suffix stays -> "Profile Banana
    (Priest)" - unless profile:name already starts with "<Class> " (SkyyProfiles 0.1.12 writes profile:name a moment before pname, so a
    page drawn in that gap never shows the class twice).
Nothing else changes (same files, same bank, same texts otherwise). Rolling back to 0.1.9 is safe (no saved-data change).
"""
import os
import ast

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "SkyyBank", "build_skyybank_0.1.9.py")
dst = os.path.join(ROOT, "SkyyBank", "build_skyybank_0.1.10.py")
raw = open(src, encoding="utf8", newline="").read()
CR, LF = chr(13), chr(10)
NL = CR + LF if (CR + LF) in raw else LF
s = raw.replace(CR + LF, LF)
OLD = s
assert 'VERSION = "0.1.9"' in s and "GENERATED by tools/bank_0_1_9_patch.py" in s and "profile:pname:" not in s, "not the generated 0.1.9 script"
CHANGES = []            # (new text, old text) of every change, in order: undone at the end to prove nothing else changed


def rep(old, new):
    global s
    n = s.count(old)
    assert n == 1, "anchor count %d: %s" % (n, old[:120])
    s = s.replace(old, new, 1)
    CHANGES.append((new, old))


_set = None
for _n in ast.parse(open(os.path.join(ROOT, "tools", "deploy_set.py"), encoding="utf-8").read()).body:
    if isinstance(_n, ast.Assign) and any(isinstance(_t, ast.Name) and _t.id == "SET" for _t in _n.targets):
        _set = dict(ast.literal_eval(_n.value))
if _set is not None and _set.get("SkyyBank") != "0.1.9":
    print("NOTE: tools/deploy_set.py SET pins SkyyBank %s, this patch derives from 0.1.9" % _set.get("SkyyBank"))

HEAD = open(__file__, encoding="utf8").read().split('"""')[1]
# ================================================================================================ docstring + version
rep('''"""SkyyBank 0.1.9 - build script (javassist via jpype). GENERATED by tools/bank_0_1_9_patch.py from the LIVE 0.1.8
(build_skyybank_0.1.8.py, the tools/deploy_set.py SET pin, itself generated by tools/bank_0_1_8_patch.py) - edit the patch, never
this file.
Run:   python build_skyybank_0.1.9.py            -> SkyyBank/SkyyBank-0.1.9.jar
       (no --deploy in this script on purpose: tools/deploy_set.py installs the whole set once Skyy says deploy)
SkyBlock-style bank: /bank (opens the bank page, 0.1.3), /bank balance, /bank status, /bank deposit <n|all|2k|1.5m>,
/bank withdraw <n|all>.
''', '''"""SkyyBank 0.1.10 - build script (javassist via jpype). GENERATED by tools/bank_0_1_10_patch.py from the LIVE 0.1.9
(build_skyybank_0.1.9.py, the tools/deploy_set.py SET pin, itself generated by tools/bank_0_1_9_patch.py) - edit the patch, never
this file.
Run:   python build_skyybank_0.1.10.py           -> SkyyBank/SkyyBank-0.1.10.jar
       (no --deploy in this script on purpose: tools/deploy_set.py installs the whole set once Skyy says deploy)
SkyBlock-style bank: /bank (opens the bank page, 0.1.3), /bank balance, /bank status, /bank deposit <n|all|2k|1.5m>,
/bank withdraw <n|all>.

''' + HEAD[HEAD.index("0.1.10 (2026-10-13)"):].strip() + '''
  CHECKED: see SkyyBank/test_skyybank_0.1.10.py.
''')
rep('VERSION = "0.1.9"\n', 'VERSION = "0.1.10"\n')

# ================================================================================================ the profile line
rep('''    Object n = br.get("profile:name:" + u.toString());
    Object c = br.get("profile:class:" + u.toString());
    if (n instanceof String && ((String) n).length() > 0) {
      String cl = (c instanceof String && ((String) c).length() > 0) ? " (" + c + ")" : "";
      return "Profile " + n + cl + "  -  every profile has its own bank. " + s;
    }''', '''    Object n = br.get("profile:name:" + u.toString());
    Object pn = br.get("profile:pname:" + u.toString());
    Object c = br.get("profile:class:" + u.toString());
    if (n instanceof String && ((String) n).length() > 0) {
      String cl = "";
      if (!(pn instanceof String) && c instanceof String && ((String) c).length() > 0 && !((String) n).startsWith(((String) c) + " "))
        cl = " (" + c + ")";
      return "Profile " + n + cl + "  -  every profile has its own bank. " + s;
    }''')

# ================================================================================================ checks on the result
assert s.count("br.get(\"profile:pname:\"") == 1 and s.count('" (" + c + ")"') == 1, "0.1.10: one profile line, the old suffix only without pname"
_u = s
for _new, _old in reversed(CHANGES):
    assert _u.count(_new) == 1, "a change is not unique any more: %s" % _new[:80]
    _u = _u.replace(_new, _old, 1)
assert _u == OLD, "the generated script differs from 0.1.9 outside the recorded changes"
compile(s, dst, "exec")
open(dst, "w", encoding="utf8", newline="").write(s.replace(LF, NL) if NL != LF else s)
print("wrote", os.path.relpath(dst, ROOT), "(%d lines; 0.1.9 had %d; %d changes)" % (s.count(LF), OLD.count(LF), len(CHANGES)))
