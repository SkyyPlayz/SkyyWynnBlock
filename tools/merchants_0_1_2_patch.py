def run_compare(out):
    from jpype import JClass
    K = Child(out)
    _jvm([B.JAVASSIST], verify=False)
    CPc = JClass("javassist.ClassPool")
    IP = JClass("javassist.bytecode.InstructionPrinter")

    def pool_of(j):
        p_ = CPc(False)
        p_.appendSystemPath()
        p_.appendClassPath(B.SERVER_JAR)
        p_.appendClassPath(j)
        return p_
    pa, pb = pool_of(OLD_JAR), pool_of(JAR)

    def members(p_, cn):
        c_ = p_.get(cn)
        d_ = {}

        def code(b_):
            mi_ = b_.getMethodInfo()
            ca_ = mi_.getCodeAttribute()
            if ca_ is None:
                return ""
            it_ = ca_.iterator()
            lines_ = []
            while it_.hasNext():
                pos_ = it_.next()
                lines_.append(re.sub(r"#\d+ = ", "", str(IP.instructionString(it_, pos_, mi_.getConstPool()))))
            return "\n".join(lines_)
        for f_ in c_.getDeclaredFields():
            d_["f " + str(f_.getName())] = str(f_.getSignature())
        for m_ in c_.getDeclaredMethods():
            d_["m " + str(m_.getName()) + str(m_.getSignature())] = code(m_)
        for m_ in c_.getDeclaredConstructors():
            d_["c " + str(m_.getSignature())] = code(m_)
        if c_.getClassInitializer() is not None:
            d_["<clinit>"] = code(c_.getClassInitializer())
        return d_
    def vtext_only(a_, b_):
        """the same code, except that some (not necessarily all) OLD version texts read VERSION (a kept history text like '0.1.21 soul
        tether' stays): every differing character lies in an occurrence of OLD in a_ that reads VERSION in b_"""
        la_, lb_ = a_.split(chr(10)), b_.split(chr(10))
        if len(la_) != len(lb_) or len(OLD) != len(VERSION):
            return a_.replace(OLD, VERSION) == b_
        for x_, y_ in zip(la_, lb_):
            if x_ == y_:
                continue
            if len(x_) != len(y_):
                return False
            for i_ in range(len(x_)):
                if x_[i_] != y_[i_] and not any(x_[s_:s_ + len(OLD)] == OLD and y_[s_:s_ + len(OLD)] == VERSION
                                                for s_ in range(max(0, i_ - len(OLD) + 1), i_ + 1)):
                    return False
        return True
    KIT = re.compile(r"skyyui \d+\.\d+ [0-9a-f]{12}")      # the config kit's build id (tools/skyyui.py hash) - a text, not code
    na, nb = jar_classes(OLD_JAR), jar_classes(JAR)
    added = sorted(set(nb) - set(na))
    K.check(added == sorted(PKG + a for a in ADDED) and not (set(na) - set(nb)), "C: classes added %s, removed %s" % (added, sorted(set(na) - set(nb))))
    diffs, vonly = {}, {}
    for cn in sorted(set(na) & set(nb)):
        ma, mb = members(pa, cn), members(pb, cn)
        for k in sorted(set(ma) | set(mb)):
            if ma.get(k) == mb.get(k):
                continue
            tag = ("+" if k not in ma else ("-" if k not in mb else "~")) + k.split("(")[0]
            if k in ma and k in mb and vtext_only(KIT.sub("skyyui KIT", ma[k]), KIT.sub("skyyui KIT", mb[k])):
                vonly.setdefault(cn[len(PKG):], []).append(tag)
                continue
