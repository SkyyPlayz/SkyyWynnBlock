    K.check({k: sorted(v) for k, v in diffs.items()} == {k: sorted(v) for k, v in ALLOWED.items()},
            "C: exactly the planned members differ: %s (planned %s)" % (diffs, ALLOWED))
    K.notes.append("C: version-text-only members: %s" % json.dumps(vonly, sort_keys=True))
    za, zb = zipfile.ZipFile(OLD_JAR), zipfile.ZipFile(JAR)
    ed = sorted(n for n in set(za.namelist()) | set(zb.namelist()) if not n.endswith(".class") and (n not in za.namelist() or n not in zb.namelist() or za.read(n) != zb.read(n)))
    ma_, mb_ = json.loads(za.read("manifest.json")), json.loads(zb.read("manifest.json"))
    ma_["Version"], ma_["Name"] = mb_.get("Version"), mb_.get("Name")
    K.check(ed == ["manifest.json"] and ma_ == mb_ and mb_.get("Version") == VERSION and mb_.get("Name") == "%s %s" % (VERSION, MOD),
            "C: non-class entries: only manifest.json changed, and only its Version + Name (%s, %s): %s" % (mb_.get("Version"), mb_.get("Name"), ed[:8]))
