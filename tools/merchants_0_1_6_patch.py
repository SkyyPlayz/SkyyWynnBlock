class Patch(object):
    def __init__(self, src, dst, tag):
        raw = open(src, "rb").read()
        self.nl = "\r\n" if b"\r\n" in raw else "\n"
        assert self.nl == "\n" or raw.count(b"\r\n") == raw.count(b"\n"), "mixed line endings in " + src
        self.s = raw.decode("utf8").replace("\r\n", "\n")
        self.old = self.s
        self.dst, self.tag = dst, tag
        self.changes = []

    def has(self, t):
        return t in self.s

    def rep(self, old, new):
        n = self.s.count(old)
        assert n == 1, "%s anchor count %d: %s" % (self.tag, n, old[:140])
        assert new and self.s.count(new) == 0, "%s: the new text is empty or already exists: %s" % (self.tag, new[:100])
        self.s = self.s.replace(old, new, 1)
        self.changes.append((new, old))

    def cut(self, start, end):
        assert self.s.count(start) == 1, "%s start anchor count %d: %s" % (self.tag, self.s.count(start), start[:120])
        i = self.s.index(start)
        j = self.s.index(end, i)
        return self.s[i:j + len(end)]

    def finish(self):
        u = self.s
        for new, old in reversed(self.changes):
            assert u.count(new) == 1, "%s: a change is not unique any more: %s" % (self.tag, new[:100])
            u = u.replace(new, old, 1)
        assert u == self.old, "%s: the generated script differs from the source outside the recorded changes" % self.tag
        compile(self.s, self.dst, "exec")
        open(self.dst, "w", encoding="utf8", newline="").write(self.s.replace(LF, self.nl) if self.nl != LF else self.s)
        print("wrote", os.path.relpath(self.dst, ROOT), "(%d lines; source %d; %d changes, undo-compare OK)" % (self.s.count(LF), self.old.count(LF), len(self.changes)))


