def mod_lines():
    out = {}
    for line in open(os.path.join(ROOT, "ARCHITECTURE.md"), encoding="utf-8"):
        m = re.match(r"\|\s*`(Skyy\w+)`\s*\|\s*(.+?)\s*\|\s*$", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def write(path, text):
    if os.path.exists(path):
        old = open(path, encoding="utf-8", errors="replace").read()
        if not old.startswith(MARK):
            return "kept (hand-written)"
        if old == text:
            return "same"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return "written"


def main():
    what = mod_lines()
    done = []
    for d in sorted(os.listdir(ROOT)):
        p = os.path.join(ROOT, d)
        if not (d.startswith("Skyy") and os.path.isdir(p)):
            continue
        low = d.lower()
        short = low[4:] if low.startswith("skyy") else low
        w = what.get(d, "A SkyWynn mod (one-liner missing in ARCHITECTURE.md - add it there and re-run tools/make_readmes.py).")
        t = MOD_TEXT.format(mark=MARK, mod=d, what=w, low=low, short=short, topic=MOD_TOPIC.get(d, "project"))
        done.append((d, write(os.path.join(p, "README.md"), t)))
    for d, (what_txt, here, new) in TOP.items():
        t = "%s\n# %s/\n\n%s\n\n## Where things are\n%s\n\n## Where new things go\n%s\n\nMap of the whole repo: `INDEX.md`. Rules: `PROJECT-RULES.md`.\n" % (
            MARK, d, what_txt, "\n".join("- " + x for x in here), "\n".join("- " + x for x in new))
        done.append((d, write(os.path.join(ROOT, d, "README.md"), t)))
    for d, r in done:
        print("%-18s %s" % (d, r))


if __name__ == "__main__":
    main()
