def pack_parse(v):
    """the Python mirror of MobCfg.packPairs: 'role[=level]' entries -> [(role, level or 0)]; a bad level = 0 (band level)"""
    out = []
    for _e in (v or "").split(","):
        _e = _e.strip()
        if not _e:
            continue
        _r, _s, _l = _e.partition("=")
        _r = _r.strip()
        _lv = int(_l.strip()) if _s and _l.strip().isdigit() and 1 <= int(_l.strip()) <= 100 else 0
        if _r:
            out.append((_r, _lv))
    return out


