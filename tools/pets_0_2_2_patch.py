        sp = _SPN.get(e.get("SpawnerId")) or []
        if len(sp) != 1:
            return None
        try:
            sd = vjson(sp[0])
        except Exception:
            return None
        pl = sd.get("ParticleLifeSpan") or {}
        plife = float(pl.get("Max", pl.get("Min", 0)) or 0)
        if syslife:
            emit = float(sl)
        else:
            if e.get("TotalSpawners", 1) in (-1, 0):
                return None
            tp = (sd.get("TotalParticles") or {}).get("Max")
            if tp is None or tp <= 0:
                if not (isinstance(sd.get("LifeSpan"), (int, float)) and sd["LifeSpan"] > 0):
                    return None
                emit = float(sd["LifeSpan"])
            else:
                rate = float((sd.get("SpawnRate") or {}).get("Min", 0) or 0)
