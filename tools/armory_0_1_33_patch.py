    lo, hi = [q for q in pts if q[0] < p], [q for q in pts if q[0] > p]
    (p0, v0), (p1, v1) = (lo[-1], hi[0]) if (lo and hi) else (pts[-2], pts[-1])
    t = (p - p0) / float(p1 - p0)
    v = v0 * (v1 / v0) ** t if (v0 > 0 and v1 > 0) else v0 + (v1 - v0) * t
    return int(math.floor(v + 0.5 + 1e-9)) if integer else round(v, nd)


