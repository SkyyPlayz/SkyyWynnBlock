def nm_interp(vals, k, nd=2, integer=False):
    """THE number rule (spec 4.3): geometric interpolation on the 15-step ladder between the nearest existing metals of vals (metal -> number;
    Onyxium, the parked tier, and other new keys never anchor); above Mithril the Adamantite -> Mithril step goes on"""
    p = LPOS[MN(k)]
