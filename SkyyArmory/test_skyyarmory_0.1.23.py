    cl_ = clsk.newInstance()
    jf(LS, "reference").set(cl_, cref)
    chunks.put(CHU.indexChunk(0, 0), cl_)
    srefs = []
    for cy_ in range(4):
        bs_, fs_, es_ = BSEC(), FSEC(), ESEC(1)
        if cy_ == 2:
            for x_ in range(32):
                for z_ in range(32):
                    bs_.set(x_, 64, z_, 1, 0, 0)
            fs_.setFluid(5, 65, 5, 1, JByte(8))
        if cy_ == 1:
            bs_.set(3, 63, 3, 2, 0, 0)
