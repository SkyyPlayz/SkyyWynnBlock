    for cn_, mapc_, ids_ in (("com.hypixel.hytale.server.core.asset.type.blocktype.config.BlockType", "com.hypixel.hytale.assetstore.map.BlockTypeAssetMap",
                              ("Empty", "Soil_Grass", "Rock_Stone")),
                             ("com.hypixel.hytale.server.core.asset.type.environment.config.Environment", "com.hypixel.hytale.assetstore.map.IndexedLookupTableAssetMap",
                              ("Env_Default", "Env_Zone1_Plains", "Env_Zone2_Savanna"))):
        A_, MP_ = JClass(cn_), JClass(mapc_)
        arr_ = JArray(JAWM)(len(ids_))
        for i_, id_ in enumerate(ids_):
            a_ = alloc(A_)
            jf(A_, "id").set(a_, id_)
            arr_[i_] = a_
        m_ = alloc(MP_)
        jf(MP_, "array").set(m_, arr_)
        st_ = alloc(HAST)
        jf(AST, "assetMap").set(st_, m_)
