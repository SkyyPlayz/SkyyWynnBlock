def _mix(h, t, f):
    a = [int(h[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(t[i:i + 2], 16) for i in (1, 3, 5)]
    return "#%02x%02x%02x" % tuple(int(round(a[i] + (b[i] - a[i]) * f)) for i in range(3))


def _fg(h):
    r, g, b = [int(h[i:i + 2], 16) / 255.0 for i in (1, 3, 5)]
    return "#10161c" if 0.299 * r + 0.587 * g + 0.114 * b > 0.55 else "#ffffff"


