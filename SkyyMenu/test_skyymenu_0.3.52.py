def run_static(out, jar, scratch, home):
    K = HK.Child(out)
    g = open(GEN, encoding="utf8", newline="").read()
    o = open(GEN_OLD, encoding="utf8", newline="").read()
    K.check(g.count('VERSION = "0.3.52"') == 1, "S VERSION")
    K.check(g.count("registerSystem(") == o.count("registerSystem(") and g.count("registerSystem(new @PKG@.InvMode())") == 1,
            "S no new registerSystem (InvMode stays the only inventory system)")
    K.check(g.count("registerCommand(") == o.count("registerCommand("), "S no new registerCommand(")
    d = os.path.join(scratch, "static")
    os.makedirs(d, exist_ok=True)
    cp = os.path.join(d, "build.py")
    ct = os.path.join(d, "test.py")
    p = subprocess.run([sys.executable, PATCH, "--out", cp, "--test-out", ct], capture_output=True, text=True)
    K.check(p.returncode == 0 and open(cp, "rb").read() == open(GEN, "rb").read() and open(ct, "rb").read() == open(os.path.abspath(__file__), "rb").read(),
            "S the patch re-runs to identical bytes (the build script AND this harness): %s" % p.stderr[-300:])
    K.check((b"\r\n" in open(GEN_OLD, "rb").read()) == (b"\r\n" in open(GEN, "rb").read()), "S line endings kept")
    # the kit: unchanged (0.3.51 uses kit 1.10 as committed)
    head = subprocess.run(["git", "-C", ROOT, "show", "HEAD:tools/skyyui.py"], capture_output=True).stdout
    cur = open(os.path.join(ROOT, "tools", "skyyui.py"), "rb").read()
    K.check(len(head) > 400000 and cur.replace(b"\r\n", b"\n") == head.replace(b"\r\n", b"\n") and b"KIT 1.10 (2026-11-14): THE SKYGLASS THEME" in cur,
            "S tools/skyyui.py = the committed kit 1.10, unchanged")
    K.check(SUI.THEMES == ("vanilla", "sky") and SUI.KIT_VERSION == "1.5", "S kit: THEMES / KIT_VERSION unchanged")
    zn, zo = zipfile.ZipFile(jar), zipfile.ZipFile(OLD_JAR)
    diff = sorted(n for n in set(zn.namelist()) | set(zo.namelist()) if not n.endswith(".class")
                  and (n not in zn.namelist() or n not in zo.namelist() or zn.read(n) != zo.read(n)))
    glass = SUI.glass_texture_files()
    K.eq(diff, ["manifest.json"], "S non-class jar entries changed = manifest only (the Skyglass textures as 0.3.50)")
    K.check(all(zn.read(k) == v for k, v in glass.items()) and all(k.startswith("Common/UI/Custom/SkyyGlass/") for k in glass),
            "S the jar's Skyglass files = the kit's generated bytes, only under Common/UI/Custom/SkyyGlass/ (%d files, sha256 %s)" % (len(glass), SUI.glass_texture_digest()[:12]))
    K.check(not [n for n in zn.namelist() if n.lower().endswith(".ui")], "S inline pages only (no .ui file)")
    # 0.3.51 (TEST 284 client crash): no built class may open the vanilla screen from the server
    _bad = lambda z_: sorted(n for n in z_.namelist() if n.endswith(".class") and (b"setPageWithWindows" in z_.read(n) or b"FieldCraftingWindow" in z_.read(n)))
    K.eq(_bad(zn), [], "S NO built class references setPageWithWindows / FieldCraftingWindow (the server never opens the vanilla screen)")
    K.eq(_bad(zipfile.ZipFile(JAR50)), ["com/skyy/menu/InvState.class"], "S ... (the scan works: 0.3.50's InvState had both)")
    # 0.3.52: our own crafting - the engine's craft steps are referenced, the server still never opens a crafting window
    _ic = zn.read("com/skyy/menu/InvCraft.class")
    K.check(all(x_ in _ic for x_ in (b"CraftRecipeEvent$Pre", b"CraftRecipeEvent$Post", b"PlayerCraftEvent", b"sacks:fn:craftPay", b"sacks:fn:craftRefund",
                                     b"sacks:fn:craftCommit", b"getContainerForItemPickup", b"addOrDropItemStack", b"craftItem", b"getBenchRecipes")),
            "S InvCraft references craftItem's steps (Pre / Post / PlayerCraftEvent, giveOutput's container pick + addOrDrop), the pay / refund / commit bridges")
    K.check(not [n for n in zn.namelist() if n.endswith(".class") and (b"CraftingWindow" in zn.read(n) or b"openWindow" in zn.read(n))],
            "S no crafting window is ever opened by the server")
    K.check(not re.search(r"(?:Vertical|Horizontal)Alignment: (?:Top|Bottom|Left|Right)\b", g), "S no Top / Bottom / Left / Right alignment value (disconnects the client)")
    # the page data in the generated script
    m = re.search(r'^IV_TABS = (\[.*?\])\n', g, re.M | re.S)
